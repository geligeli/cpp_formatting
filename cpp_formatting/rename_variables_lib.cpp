// The canonical rename-map key for the member a MemberExpr resolves to, or null
// if the member is not one of the kinds we rename.  Mirrors the dispatch in
// ApplyRenamesVisitor::VisitMemberExpr.
static const Decl* memberExprKey(const MemberExpr* E) {
  if (const auto* FD = dyn_cast<FieldDecl>(E->getMemberDecl()))
    return primaryTemplateMember(FD);
  if (const auto* VD = dyn_cast<VarDecl>(E->getMemberDecl()))
    return primaryTemplateStaticMember(VD)->getCanonicalDecl();
  if (const auto* MD = dyn_cast<CXXMethodDecl>(E->getMemberDecl()))
    return primaryTemplateMethod(MD)->getCanonicalDecl();
  return nullptr;
}

// The canonical rename-map key for what a DeclRefExpr refers to, or null if it
// is not one of the kinds we rename.  Mirrors the dispatch in
// ApplyRenamesVisitor::VisitDeclRefExpr.
static const Decl* declRefKey(const DeclRefExpr* E) {
  const ValueDecl* D = E->getDecl();
  if (!D->getDeclName().isIdentifier()) return nullptr;
  if (const auto* VD = dyn_cast<VarDecl>(D))
    return VD->isStaticDataMember()
               ? primaryTemplateStaticMember(VD)->getCanonicalDecl()
               : VD->getCanonicalDecl();
  if (const auto* FD = dyn_cast<FieldDecl>(D)) return primaryTemplateMember(FD);
  if (const auto* MD = dyn_cast<CXXMethodDecl>(D))
    return primaryTemplateMethod(MD)->getCanonicalDecl();
  return nullptr;
}

// Pass A (cheap, no instantiations): find the locations of template-dependent
// member tokens (`x.val` where x is dependent) that live in files we own.  If
// none exist we can skip the expensive instantiation walk of Pass B entirely.
// The dependent tokens spelled in files this TU owns: location -> spelling.
using DependentTokens = std::map<std::pair<std::string, unsigned>, std::string>;

class DependentTokenCollector
    : public RecursiveASTVisitor<DependentTokenCollector> {
 public:
  DependentTokenCollector(SourceManager& SM, const FileSet& CollectFrom,
                          DependentTokens& Locs)
      : SM(SM), CollectFrom(CollectFrom), Locs(Locs) {}

  // `typename T::Inner`, and the `Inner` of `T::Inner::x`: a type name that
  // resolves only per instantiation, for the type scope.
  bool VisitDependentNameTypeLoc(DependentNameTypeLoc TL) {
    if (const IdentifierInfo* II = TL.getTypePtr()->getIdentifier())
      add(TL.getNameLoc(), II->getName());
    return true;
  }
  bool TraverseNestedNameSpecifierLoc(NestedNameSpecifierLoc NNS) {
    using Base = RecursiveASTVisitor<DependentTokenCollector>;
    for (NestedNameSpecifierLoc L = NNS; L; L = L.getPrefix()) {
      const NestedNameSpecifier* S = L.getNestedNameSpecifier();
      if (S && S->getKind() == NestedNameSpecifier::Identifier)
        if (const IdentifierInfo* II = S->getAsIdentifier())
          add(L.getLocalBeginLoc(), II->getName());
    }
    return Base::TraverseNestedNameSpecifierLoc(NNS);
  }

  bool VisitCXXDependentScopeMemberExpr(CXXDependentScopeMemberExpr* E) {
    SourceLocation Loc = E->getMemberLoc();
    // A dependent token written as a macro *argument* is spelled at the call
    // site, so it is an ordinary candidate -- `EXPECT_FALSE(this->table_)` in a
    // TYPED_TEST is the common shape.  ownedKey() keys by the spelling, so the
    // recorder and the applier agree on the same location.  Only a token with
    // no spelling of its own (macro body, ## paste) is skipped.
    if (!rewriteLocFor(Loc, SM).isValid()) return true;
    const IdentifierInfo* II = E->getMember().getAsIdentifierInfo();
    if (!II) return true;
    if (auto Key = ownedKey(Loc, SM, CollectFrom))
      Locs.emplace(*Key, II->getName().str());
    return true;
  }

  // `Helper<T>::member` -- a qualified *name* whose lookup is deferred to
  // instantiation, not a member access on an object.  Same problem and same
  // treatment as `x.member`: the token is spelled here, and which entity it
  // names is only learned from an instantiation, usually in another TU.
  bool VisitDependentScopeDeclRefExpr(DependentScopeDeclRefExpr* E) {
    SourceLocation Loc = E->getLocation();
    if (!rewriteLocFor(Loc, SM).isValid()) return true;
    const IdentifierInfo* II = E->getDeclName().getAsIdentifierInfo();
    if (!II) return true;
    if (auto Key = ownedKey(Loc, SM, CollectFrom))
      Locs.emplace(*Key, II->getName().str());
    return true;
  }

 private:
  void add(SourceLocation Loc, StringRef Name) {
    if (!rewriteLocFor(Loc, SM).isValid()) return;
    if (auto Key = ownedKey(Loc, SM, CollectFrom))
      Locs.emplace(*Key, Name.str());
  }

  SourceManager& SM;
  const FileSet& CollectFrom;
  DependentTokens& Locs;
};

// Pass B (walks template instantiations): for every resolved member access that
// lands on a known dependent-token location, record the new name it resolves
// to.  A binding to a member that is not being renamed vetoes the location, so
// a template instantiated with a type outside the FileSet is never left with a
// dangling member access.
// Renamed declarations indexed by their *old* name, for the backstops that
// decline a rename by name when a reference could not be tied to its
// declaration (see ApplyRenamesVisitor::handle and the recorder's resolve()).
using RenamesByOldName = std::multimap<std::string, const Decl*>;

static RenamesByOldName indexByOldName(const RenameMap& Renames) {
  RenamesByOldName Out;
  for (const auto& [Key, NewName] : Renames)
    if (const auto* ND = dyn_cast<NamedDecl>(Key))
      if (ND->getDeclName().isIdentifier())
        Out.emplace(ND->getName().str(), Key);
  return Out;
}

// Declines every rename whose declaration is spelled \p OldName.  The blunt
// instrument for when a reference is known to name *something* being renamed
// but cannot be tied to which declaration; over-declining is the safe side.
static void vetoByName(RenameVetoes* Vetoes, RenameConflicts* Conflicts,
                       const RenamesByOldName& ByOldName, SourceManager& SM,
                       llvm::StringRef OldName, const std::string& Reason) {
  if (!Vetoes) return;
  // The name itself, so TUs that declare something of this name without
  // seeing this reference decline it too (see nameVetoKey).
  const std::pair<std::string, unsigned> NK = nameVetoKey(OldName);
  Vetoes->try_emplace(NK, RenameVeto{NK.first, 0, OldName.str(), Reason});
  auto Range = ByOldName.equal_range(OldName.str());
  for (auto It = Range.first; It != Range.second; ++It) {
    const Decl* Key = It->second;
    if (!addRenameVeto(Vetoes, Key, SM, OldName, Reason) || !Conflicts)
      continue;
    const auto* ND = cast<NamedDecl>(Key);
    const PresumedLoc PL = SM.getPresumedLoc(ND->getLocation());
    Conflicts->push_back(RenameConflict{
        PL.isValid() ? PL.getFilename() : "", PL.isValid() ? PL.getLine() : 0,
        PL.isValid() ? PL.getColumn() : 0, OldName.str(), "", Reason});
  }
}

class RecordDependentResolutionsVisitor
    : public RecursiveASTVisitor<RecordDependentResolutionsVisitor> {
 public:
  RecordDependentResolutionsVisitor(
      SourceManager& SM, const RenameMap& Renames, const FileSet& CollectFrom,
      const DependentTokens& DependentLocs, DependentResolutions& DepRes,
      RenameVetoes* Vetoes, RenameConflicts* Conflicts,
      const RenamesByOldName& ByOldName, VariableScope Scope,
      llvm::ArrayRef<VariableScope> AllScopes)
      : SM(SM),
        Renames(Renames),
        CollectFrom(CollectFrom),
        DependentLocs(DependentLocs),
        DepRes(DepRes),
        Vetoes(Vetoes),
        Conflicts(Conflicts),
        ByOldName(ByOldName),
        Scope(Scope),
        AllScopes(AllScopes) {}

  bool shouldVisitTemplateInstantiations() const { return true; }

  bool VisitMemberExpr(MemberExpr* E) {
    SourceLocation Loc = E->getMemberLoc();
    if (!rewriteLocFor(Loc, SM).isValid()) return true;
    auto Key = ownedKey(Loc, SM, CollectFrom);
    if (!Key || DependentLocs.find(*Key) == DependentLocs.end()) return true;
    const Decl* MemberKey = memberExprKey(E);
    if (!MemberKey) return true;
    const NamedDecl* Member = E->getMemberDecl();
    if (!Member->getDeclName().isIdentifier()) return true;
    llvm::StringRef Old = Member->getName();
    // A member of an anonymous union is reached through an implicit MemberExpr
    // on the union's own unnamed field, at the *same* location as the token.
    // That node names nothing the user could spell; treating it as "a member
    // not being renamed" is what vetoed every `this->status_` in abseil.
    if (Old.empty()) return true;
    resolve(*Key, MemberKey, Member, Old);
    return true;
  }

  // The resolved form of a dependent type name: `typename T::Inner` in the
  // instantiation is a TagTypeLoc (or a typedef, or a template) at the
  // pattern's token.
  bool VisitTagTypeLoc(TagTypeLoc TL) {
    if (const TagDecl* D = TL.getDecl())
      resolveAt(TL.getNameLoc(), typeKey(D), D);
    return true;
  }
  bool VisitTypedefTypeLoc(TypedefTypeLoc TL) {
    if (const TypedefNameDecl* D = TL.getTypedefNameDecl())
      resolveAt(TL.getNameLoc(), D->getCanonicalDecl(), D);
    return true;
  }
  bool VisitTemplateSpecializationTypeLoc(TemplateSpecializationTypeLoc TL) {
    if (const TemplateDecl* TD =
            TL.getTypePtr()->getTemplateName().getAsTemplateDecl())
      resolveAt(TL.getTemplateNameLoc(), templateKey(TD), TD);
    return true;
  }

  // The resolved form of a qualified dependent name: in an instantiation
  // `Helper<T>::member` becomes an ordinary DeclRefExpr whose location still
  // points at the token in the pattern.
  bool VisitDeclRefExpr(DeclRefExpr* E) {
    SourceLocation Loc = E->getLocation();
    if (!rewriteLocFor(Loc, SM).isValid()) return true;
    auto Key = ownedKey(Loc, SM, CollectFrom);
    if (!Key || DependentLocs.find(*Key) == DependentLocs.end()) return true;
    const Decl* RefKey = declRefKey(E);
    if (!RefKey) return true;
    llvm::StringRef Old = E->getDecl()->getName();
    if (Old.empty()) return true;
    resolve(*Key, RefKey, E->getDecl(), Old);
    return true;
  }

 private:
  void resolveAt(SourceLocation Loc, const Decl* Key, const NamedDecl* D) {
    if (!Key || !D->getDeclName().isIdentifier() || D->getName().empty())
      return;
    if (!rewriteLocFor(Loc, SM).isValid()) return;
    auto TK = ownedKey(Loc, SM, CollectFrom);
    if (!TK || DependentLocs.find(*TK) == DependentLocs.end()) return;
    resolve(*TK, Key, D, D->getName());
  }

  // One instantiation's answer for the token at \p TokenKey: it binds to
  // \p Member, whose rename-map key is \p MemberKey.
  void resolve(const std::pair<std::string, unsigned>& TokenKey,
               const Decl* MemberKey, const NamedDecl* Member,
               llvm::StringRef Old) {
    auto It = Renames.find(MemberKey);
    if (It == Renames.end()) {
      // Not renamed by this rule, so the token must keep its spelling.  That
      // is the end of it unless this rule renames *another* declaration of
      // the same name: then some instantiation may bind the token to that one,
      // and a token that keeps its spelling while one of its targets is
      // renamed is a build break in that instantiation.  Renaming is
      // all-or-nothing per token, so every declaration of the spelling is
      // declined -- by name, since the other targets need not be visible from
      // here -- unless the binding is simply another rule's business: a
      // member in a file we format, outside this rule's scope, inside some
      // other configured rule's (whose own recorder makes the same call).
      // Three shapes are declined: a member of a type outside the files being
      // formatted (protobuf's TcParser::GetTable spells T::_table_ for every
      // message class, checked-in and generated alike); a member this rule
      // declined (MicroString::kInlineCapacity, captured by a parameter, next
      // to the derived MicroStringExtraImpl::kInlineCapacity, which renamed);
      // and an instantiated member the tool could not map back to its pattern,
      // which is a mapping failure rather than a different entity.
      vetoResolution(DepRes, TokenKey);
      if (ByOldName.count(Old.str()) == 0) return;
      const bool Owned = shouldCollect(Member->getLocation(), SM, CollectFrom);
      if (Owned && !matchesScope(Member, Scope) && matchesAnyScope(Member)) {
        return;
      }
      std::string Reason;
      if (!Owned) {
        Reason =
            "a template-dependent use of the name also resolves to a member "
            "of a type outside the files being formatted, so the use cannot "
            "be rewritten";
      } else if (isClassMemberDecl(Member) &&
                 isInTemplateInstantiation(Member)) {
        Reason =
            "a template-dependent use resolves to an instantiated member "
            "that could not be mapped to its declaration";
      } else {
        Reason =
            "a template-dependent use of the name also resolves to a "
            "declaration that is not being renamed, so the use cannot be "
            "rewritten";
      }
      const PresumedLoc PL = SM.getPresumedLoc(Member->getLocation());
      if (PL.isValid())
        Reason += " (" + Member->getQualifiedNameAsString() + " at " +
                  relativizeToCwd(PL.getFilename()) + ":" +
                  std::to_string(PL.getLine()) + ")";
      vetoByName(Vetoes, Conflicts, ByOldName, SM, Old, Reason);
      return;
    }
    std::pair<std::string, unsigned> Owner = renameOwnerKey(MemberKey, SM);
    std::pair<std::string, unsigned> RelOwner{relativizeToCwd(Owner.first),
                                              Owner.second};
    // Instantiations that disagree leave the token unrewritable, so *both*
    // members it can name must keep their old names -- the veto has to reach
    // the declarations, not just the token, or each is renamed and this one
    // use is left spelling neither.
    auto Existing = DepRes.find(TokenKey);
    if (Existing != DepRes.end() && Existing->second.HasName &&
        !Existing->second.Vetoed && Existing->second.NewName != It->second) {
      const DependentResolution& Prev = Existing->second;
      const std::string Reason =
          "template instantiations resolve one dependent use to different "
          "members";
      if (Vetoes && !Prev.OwnerFile.empty())
        Vetoes->try_emplace(
            std::make_pair(Prev.OwnerFile, Prev.OwnerOffset),
            RenameVeto{Prev.OwnerFile, Prev.OwnerOffset, Prev.OldName, Reason});
      if (Vetoes)
        Vetoes->try_emplace(
            RelOwner,
            RenameVeto{RelOwner.first, RelOwner.second, Old.str(), Reason});
      if (Conflicts) {
        const PresumedLoc PL = SM.getPresumedLoc(Member->getLocation());
        Conflicts->push_back(RenameConflict{
            PL.isValid() ? PL.getFilename() : "",
            PL.isValid() ? PL.getLine() : 0, PL.isValid() ? PL.getColumn() : 0,
            Old.str(), It->second, Reason});
      }
    }
    recordResolution(DepRes, TokenKey, It->second, Old, Old.size(),
                     std::move(RelOwner));
  }

  bool matchesAnyScope(const NamedDecl* D) const {
    for (VariableScope S : AllScopes)
      if (matchesScope(D, S)) return true;
    return AllScopes.empty() && matchesScope(D, Scope);
  }

  SourceManager& SM;
  const RenameMap& Renames;
  const FileSet& CollectFrom;
  const DependentTokens& DependentLocs;
  DependentResolutions& DepRes;
  RenameVetoes* Vetoes;
  RenameConflicts* Conflicts;
  const RenamesByOldName& ByOldName;
  VariableScope Scope;
  llvm::ArrayRef<VariableScope> AllScopes;
};

// ---------------------------------------------------------------------------
// Pass 2: apply renames at every declaration and use site
//
// Runs twice over each TU.  The Scan pass rewrites nothing; it only looks for
// references the Rewriter cannot express -- a token spelled in a macro body, or
// one synthesized by token pasting -- and vetoes the declaration they belong
// to.  The Rewrite pass then applies whatever survived.  Scanning first is what
// makes a rename all-or-nothing within a TU: no edit is buffered until every
// reference in that TU has been seen.
// ---------------------------------------------------------------------------

enum class ApplyMode { Scan, Rewrite };

// ---------------------------------------------------------------------------
// Would the new name still find the member from where it is used?
// ---------------------------------------------------------------------------
//
// collides() asks whether the new name is taken in the *declaring* class.  But
// an access `obj.m` (or `this->m`, or plain `m` inside a member function) looks
// the name up starting at the *object's* class and stops at the first class on
// the derivation path that has it.  So a derived class that declares the new
// name -- abseil's StatusOr<T> has a method status() while its base
// StatusOrData<T> has the field status_ -- hides the renamed member from every
// access made through the derived type: `this->status_` rewritten to
// `this->status` names the method.  The check has to be made per use, against
// the class the use goes through.

// The first declaration of \p Name in a class on a derivation path from
// \p From down to (but excluding) \p Home, or null.  Home itself is
// collides()'s business.
static const NamedDecl* hiderOnPath(
    const CXXRecordDecl* From, const CXXRecordDecl* Home, DeclarationName Name,
    llvm::SmallPtrSetImpl<const CXXRecordDecl*>& Visited) {
  if (!From || From->getCanonicalDecl() == Home->getCanonicalDecl())
    return nullptr;
  From = From->getDefinition();
  if (!From || !Visited.insert(From).second) return nullptr;
  if (!From->isDerivedFrom(Home)) return nullptr;  // not on a path to Home
  for (const NamedDecl* ND : From->lookup(Name))
    if (!ND->isImplicit()) return ND;
  for (const CXXBaseSpecifier& B : From->bases())
    if (const NamedDecl* H =
            hiderOnPath(B.getType()->getAsCXXRecordDecl(), Home, Name, Visited))
      return H;
  return nullptr;
}

// The object expression a member access is really made on.  A member of an
// anonymous struct or union is reached through an implicit MemberExpr on the
// unnamed field -- `init_value_` inside `union { InitValue init_value_; }` is
// `this-><anon>.init_value_` -- and every check that asks "what is the access
// made on" has to look through that: protobuf's `auto init_value = init_value_`
// was not recognised as an implicit-this access, so the local capture rule
// never ran, and the rewrite produced `auto init_value = init_value;`.
static const Expr* peelAnonymousMemberBase(const Expr* Base) {
  for (unsigned Guard = 0; Base && Guard < 32; ++Guard) {
    const auto* ME = dyn_cast<MemberExpr>(Base->IgnoreImpCasts());
    if (!ME) break;
    const auto* FD = dyn_cast<FieldDecl>(ME->getMemberDecl());
    if (!FD || !FD->isAnonymousStructOrUnion()) break;
    Base = ME->getBase();
  }
  return Base;
}

// The declaration that would capture \p E's member access once the member is
// renamed to \p NewName, or null if the access would still bind the member.
// A qualified access (`Base::m`) starts lookup at the qualifier and is safe.
static const NamedDecl* renameWouldBeHiddenAt(const MemberExpr* E,
                                              llvm::StringRef NewName) {
  if (E->getQualifier()) return nullptr;
  const NamedDecl* Member = E->getMemberDecl();
  const CXXRecordDecl* Home = lookupHomeOf(Member);
  if (!Home) return nullptr;
  // Sema has already cast the object to the class that declares the member
  // (an implicit UncheckedDerivedToBase), so the base expression's type is
  // Home; the class the *user* went through is underneath the casts.
  QualType T =
      peelAnonymousMemberBase(E->getBase())->IgnoreImpCasts()->getType();
  if (E->isArrow()) {
    const auto* PT = T->getAs<PointerType>();
    if (!PT) return nullptr;
    T = PT->getPointeeType();
  }
  const CXXRecordDecl* From = T->getAsCXXRecordDecl();
  if (!From) return nullptr;
  DeclarationName DN(&Member->getASTContext().Idents.get(NewName));
  llvm::SmallPtrSet<const CXXRecordDecl*, 8> Visited;
  return hiderOnPath(From, Home, DN, Visited);
}

// ---------------------------------------------------------------------------
// Would the new name hide something the scope already uses?
// ---------------------------------------------------------------------------
//
// collides() asks whether the new name is *taken* in the scope the rename
// introduces it into, and scan() case (b) whether a local of the new name
// would capture a use of the member.  This is the third direction: the new
// name may already be *used*, unqualified, inside that scope to mean something
// from further out, which the renamed declaration would then hide.
// game_arena's Engine::capabilities() renamed to Capabilities() is the name of
// its own return type, a struct in the enclosing namespace: inside the class
// and in every class derived from it, `Capabilities` then finds the member
// function first (GCC rejects the base with -Wchanges-meaning and every
// override with "does not name a type").  highway's AlignedDeleter::free_
// renamed to free sits next to a static member function that calls ::free
// unqualified.  Both are one question, asked per use: after the rename, would
// unqualified lookup of this name from this site reach the renamed declaration
// before it reaches what the name means today?

// The identity of a scope for that question.  An instantiation counts as its
// pattern, so a site inside Outer<int>::f() and a rename keyed on the
// pattern's member compare equal.
static const void* contextKey(const DeclContext* DC) {
  if (const auto* RD = dyn_cast<CXXRecordDecl>(DC)) {
    if (const CXXRecordDecl* P = instantiationPattern(RD)) RD = P;
    return RD->getCanonicalDecl();
  }
  if (const auto* FD = dyn_cast<FunctionDecl>(DC)) {
    if (const FunctionDecl* P = FD->getTemplateInstantiationPattern()) FD = P;
    return FD->getCanonicalDecl();
  }
  return DC->getPrimaryContext();
}

// The scope a declaration's name is found in by unqualified lookup: the
// nearest enclosing function, named class, or namespace.  An unscoped enum and
// an anonymous struct or union are looked through, as lookup looks through
// them.
static const DeclContext* homeScopeOf(const Decl* D) {
  for (const DeclContext* DC = D->getDeclContext(); DC; DC = DC->getParent()) {
    if (isa<FunctionDecl>(DC) || isa<NamespaceDecl>(DC) ||
        isa<TranslationUnitDecl>(DC))
      return DC;
    if (const auto* RD = dyn_cast<CXXRecordDecl>(DC);
        RD && !RD->isAnonymousStructOrUnion())
      return DC;
  }
  return nullptr;
}

// True when \p K has a (possibly indirect) base whose scope identity is
// \p HomeKey.  A dependent base is skipped: the scan pass visits the
// instantiations too, and checks the same use there with the bases resolved.
static bool derivesFrom(const CXXRecordDecl* K, const void* HomeKey,
                        llvm::SmallPtrSetImpl<const CXXRecordDecl*>& Visited) {
  K = K->getDefinition();
  if (!K || !Visited.insert(K).second) return false;
  for (const CXXBaseSpecifier& B : K->bases()) {
    const CXXRecordDecl* RB = B.getType()->getAsCXXRecordDecl();
    if (!RB) continue;
    if (contextKey(RB) == HomeKey || derivesFrom(RB, HomeKey, Visited))
      return true;
  }
  return false;
}

// The names a function declares: parameters and local variables (ParmVarDecl is
// a VarDecl, so one case covers both).  A rename onto one of these would be
// captured by it at every use inside that function.
class LocalNameCollector : public RecursiveASTVisitor<LocalNameCollector> {
 public:
  explicit LocalNameCollector(std::set<std::string>& Out) : Out(Out) {}

  bool VisitVarDecl(VarDecl* D) {
    if (D->getDeclName().isIdentifier() && !D->getName().empty())
      Out.insert(D->getName().str());
    return true;
  }

 private:
  std::set<std::string>& Out;
};

class ApplyRenamesVisitor : public RecursiveASTVisitor<ApplyRenamesVisitor> {
 public:
  ApplyRenamesVisitor(Rewriter& RW, SourceManager& SM, const RenameMap& Renames,
                      const FileSet& CollectFrom, DependentResolutions* DepRes,
                      LintReport* Report, std::string RuleId, EditReport* Edits,
                      ApplyMode Mode = ApplyMode::Rewrite,
                      RenameVetoes* Vetoes = nullptr,
                      RenameConflicts* Conflicts = nullptr)
      : RW(RW),
        SM(SM),
        Renames(Renames),
        CollectFrom(CollectFrom),
        DepRes(DepRes),
        Report(Report),
        RuleId(std::move(RuleId)),
        Edits(Edits),
        Mode(Mode),
        Vetoes(Vetoes),
        Conflicts(Conflicts) {
    if (Mode == ApplyMode::Scan) {
      ByOldName = indexByOldName(Renames);
      for (const auto& [Key, NewName] : Renames)
        if (const auto* ND = dyn_cast<NamedDecl>(Key);
            ND && ND->getDeclName().isIdentifier())
          ByNewName.emplace(NewName, NewNameEntry{Key, ND->getName().str()});
    }
  }

  // Scan mode only: lets the scan read macro definitions (see
  // declaredThroughPastingMacro).  Set after construction, when a
  // Preprocessor is available.
  void setPreprocessor(Preprocessor* P) { PP = P; }

  // Scan mode only: the macro-argument tokens the preprocessor consumed, which
  // the spelling audit must not count (see ConsumedMacroArgs).
  void setConsumedMacroArgs(const ConsumedMacroArgs* C) { Consumed = C; }

  // While scanning, every function pushes the names it declares (parameters and
  // locals), so scan() can tell whether a rename would be captured by one.  The
  // whole function is collected up front rather than tracked as the walk
  // descends: that over-approximates -- a local in a sibling block does not
  // really shadow -- and over-vetoing is the safe direction here, since the
  // failure it prevents is silent.
  bool TraverseDecl(Decl* D) {
    using Base = RecursiveASTVisitor<ApplyRenamesVisitor>;
    if (Mode != ApplyMode::Scan || !D) return Base::TraverseDecl(D);
    // Inside a template instantiation nothing counts as "seen" for the
    // spelling audit: the rewrite pass never walks instantiations, so a token
    // that only an instantiated node accounts for -- the call Init(p) in a
    // constructor template, which the pattern holds as an unresolved overload
    // set -- would be left behind.  The audit must see it as unaccounted.
    const bool Root = isInstantiationRoot(D);
    // An explicit instantiation (`template struct Box<char>;`) is a root --
    // its members are compiler-made -- but its own name and template
    // arguments are written by the user and rewritten by the rewrite pass, so
    // they count as seen.  Traversed here, before the depth goes up.
    if (Root)
      if (const auto* Spec = dyn_cast<ClassTemplateSpecializationDecl>(D)) {
        const TemplateSpecializationKind K =
            Spec->getTemplateSpecializationKind();
        if (K == TSK_ExplicitInstantiationDeclaration ||
            K == TSK_ExplicitInstantiationDefinition) {
          markSeen(Spec->getLocation());
          if (const ASTTemplateArgumentListInfo* Args =
                  Spec->getTemplateArgsAsWritten())
            for (const TemplateArgumentLoc& AL : Args->arguments())
              Base::TraverseTemplateArgumentLoc(AL);
        }
      }
    if (Root) ++InstantiationDepth;
    auto* FD = dyn_cast<FunctionDecl>(D);
    if (FD) {
      LocalNames.emplace_back();
      LocalNameCollector(LocalNames.back()).TraverseDecl(FD);
    }
    // The scope a use is looked up from, for the capture check: the innermost
    // declaration context being traversed (its semantic parents give the rest
    // of the path, so an out-of-line member definition still sees its class).
    const auto* DC = dyn_cast<DeclContext>(D);
    if (DC) ContextStack.push_back(DC);
    const bool Result = Base::TraverseDecl(D);
    if (DC) ContextStack.pop_back();
    if (FD) LocalNames.pop_back();
    if (Root) --InstantiationDepth;
    return Result;
  }

  // A lambda's body is traversed from the expression, not from its closure
  // class, so the call operator is pushed here: the lambda's own locals live
  // in it, and its semantic parents lead back to the enclosing function.
  bool TraverseLambdaExpr(LambdaExpr* E) {
    using Base = RecursiveASTVisitor<ApplyRenamesVisitor>;
    if (Mode != ApplyMode::Scan || !E) return Base::TraverseLambdaExpr(E);
    ContextStack.push_back(E->getCallOperator());
    const bool Result = Base::TraverseLambdaExpr(E);
    ContextStack.pop_back();
    return Result;
  }

  // A name written with a qualifier (`ns::T`) or an elaborated-type-specifier
  // (`struct T`) is not found by ordinary unqualified lookup -- the first
  // starts at the qualifier, the second finds only class names -- so the type
  // loc it names is excused from the capture check.  Only that loc: a template
  // argument inside it (`ns::Vec<T>`) is still an unqualified use of T.
  bool TraverseElaboratedTypeLoc(ElaboratedTypeLoc TL) {
    using Base = RecursiveASTVisitor<ApplyRenamesVisitor>;
    if (Mode == ApplyMode::Scan &&
        (TL.getQualifierLoc().hasQualifier() ||
         TL.getTypePtr()->getKeyword() != ElaboratedTypeKeyword::None))
      QualifiedNamedLocs.insert(TL.getNamedTypeLoc().getOpaqueData());
    return Base::TraverseElaboratedTypeLoc(TL);
  }

  // The unqualified uses the capture check looks at: a name, a member access,
  // an overload set, and every spelling of a type.
  bool VisitUnresolvedLookupExpr(UnresolvedLookupExpr* E) {
    if (Mode == ApplyMode::Scan && !E->getQualifier() && E->getNumDecls() > 0)
      checkCaptureOfName((*E->decls_begin())->getUnderlyingDecl(),
                         E->getNameLoc());
    return true;
  }
  bool VisitUnresolvedMemberExpr(UnresolvedMemberExpr* E) {
    if (Mode != ApplyMode::Scan || E->getQualifier() || E->getNumDecls() == 0)
      return true;
    const NamedDecl* First = (*E->decls_begin())->getUnderlyingDecl();
    if (E->isImplicitAccess())
      checkCaptureOfName(First, E->getMemberLoc());
    else
      checkCaptureThrough(
          peelAnonymousMemberBase(E->getBase())->IgnoreImpCasts()->getType(),
          E->isArrow(), First, E->getMemberLoc());
    return true;
  }
  bool VisitRecordTypeLoc(RecordTypeLoc TL) {
    checkCaptureOfType(TL, TL.getDecl());
    return true;
  }
  bool VisitEnumTypeLoc(EnumTypeLoc TL) {
    checkCaptureOfType(TL, TL.getDecl());
    return true;
  }
  bool VisitTypedefTypeLoc(TypedefTypeLoc TL) {
    checkCaptureOfType(TL, TL.getTypedefNameDecl());
    if (const TypedefNameDecl* D = TL.getTypedefNameDecl())
      handle(TL.getNameLoc(), D->getCanonicalDecl(), D->getName(),
             isUnqualifiedType(TL));
    return true;
  }
  bool VisitInjectedClassNameTypeLoc(InjectedClassNameTypeLoc TL) {
    checkCaptureOfType(TL, TL.getDecl());
    if (const CXXRecordDecl* D = TL.getDecl())
      handle(TL.getNameLoc(), typeKey(D), D->getName(), isUnqualifiedType(TL));
    return true;
  }
  bool VisitTemplateTypeParmTypeLoc(TemplateTypeParmTypeLoc TL) {
    checkCaptureOfType(TL, TL.getDecl());
    return true;
  }
  bool VisitUnresolvedUsingTypeLoc(UnresolvedUsingTypeLoc TL) {
    checkCaptureOfType(TL, TL.getDecl());
    return true;
  }
  bool VisitUsingTypeLoc(UsingTypeLoc TL) {
    checkCaptureOfType(TL, TL.getFoundDecl());
    if (const UsingShadowDecl* S = TL.getFoundDecl())
      if (const Decl* Key = typeLikeKey(S->getTargetDecl()))
        handle(TL.getNameLoc(), Key, S->getTargetDecl()->getName(),
               isUnqualifiedType(TL));
    return true;
  }
  bool VisitTemplateSpecializationTypeLoc(TemplateSpecializationTypeLoc TL) {
    const TemplateDecl* TD =
        TL.getTypePtr()->getTemplateName().getAsTemplateDecl();
    checkCaptureOfType(TL, TD);
    if (TD)
      handle(TL.getTemplateNameLoc(), templateKey(TD), TD->getName(),
             isUnqualifiedType(TL));
    return true;
  }
  bool VisitDeducedTemplateSpecializationTypeLoc(
      DeducedTemplateSpecializationTypeLoc TL) {
    const TemplateDecl* TD =
        TL.getTypePtr()->getTemplateName().getAsTemplateDecl();
    checkCaptureOfType(TL, TD);
    if (TD)
      handle(TL.getTemplateNameLoc(), templateKey(TD), TD->getName(),
             isUnqualifiedType(TL));
    return true;
  }

  // Only while scanning.  A dependent token spelled in a macro body has no
  // MemberExpr in the pattern -- which member it names is known only in an
  // instantiation -- so without this the member would be renamed at its
  // declaration and the macro left spelling the old name.  The rewrite pass
  // must never walk instantiations: their locations point back into the
  // pattern, which is rewritten once through the pattern's own nodes.
  bool shouldVisitTemplateInstantiations() const {
    return Mode == ApplyMode::Scan;
  }

  auto rewriteLoc(SourceLocation Loc) const -> SourceLocation {
    return rewriteLocFor(Loc, SM);
  }

  // Which files this pass may rewrite.  In a direct run, only this TU's own
  // main file -- the drivers merge whole rewritten file contents, so a second
  // writer would lose one of them.  In Emit mode every owned file, because a
  // header is not a translation unit there: it is parsed wherever it is
  // included, and aggregation unions the records per file and dedups the
  // identical ones.  See isRewritableFile() in tu_driver.h.
  auto owns(SourceLocation Loc) const -> bool {
    SourceLocation RL = rewriteLoc(Loc);
    if (!RL.isValid()) return false;
    if (Edits) return isRewritableFile(RL, SM, CollectFrom);
    return SM.getFileID(RL) == SM.getMainFileID();
  }

  // Applies one rewrite and, in Lint mode, records the matching diagnostic; in
  // Emit mode, appends a structured edit record instead of (only) rewriting.
  void renameAt(SourceLocation Loc, const Decl* Key, StringRef OldName,
                const std::string& NewName) {
    Loc = rewriteLoc(Loc);
    if (Loc.isInvalid()) return;
    // One spelled token can arrive through several AST nodes when a macro
    // expands the same argument more than once (`#define TWICE(x) ((x)+(x))`).
    if (!Rewritten.insert(SM.getDecomposedLoc(Loc)).second) return;
    RW.ReplaceText(Loc, OldName.size(), NewName);
    if (Report) {
      PresumedLoc PLoc = SM.getPresumedLoc(Loc);
      Report->add({PLoc.isValid() ? PLoc.getFilename() : "", PLoc.getLine(),
                   PLoc.getColumn(), RuleId,
                   "'" + OldName.str() + "' should be '" + NewName + "'"});
    }
    if (Edits) {
      std::pair<std::string, unsigned> K = locKey(Loc, SM);
      std::pair<std::string, unsigned> Owner = ownerKey(Key);
      Edits->Edits.push_back({relativizeToCwd(K.first), K.second,
                              static_cast<unsigned>(OldName.size()),
                              OldName.str(), NewName,
                              relativizeToCwd(Owner.first), Owner.second});
    }
  }

  bool VisitFieldDecl(FieldDecl* D) {
    // The scan pass walks instantiations, where every field is a fresh
    // declaration whose location points back at the pattern; keying it by
    // itself would make it look like an unmapped member (see handle()).
    const Decl* Key = primaryTemplateMember(D);
    declaredThroughPastingMacro(D, Key);
    handle(D->getLocation(), Key, D->getName());
    return true;
  }

  bool VisitVarDecl(VarDecl* D) {
    const Decl* Key = D->isStaticDataMember()
                          ? primaryTemplateStaticMember(D)->getCanonicalDecl()
                          : D->getCanonicalDecl();
    declaredThroughPastingMacro(D, Key);
    handle(D->getLocation(), Key, D->getName());
    return true;
  }

  bool VisitCXXMethodDecl(CXXMethodDecl* D) {
    // Constructors, destructors, conversion functions and operators have no
    // plain identifier; getName() asserts on those.  They are never renamed
    // (isRenamableMethod), so they are never in the map either.
    if (!D->getDeclName().isIdentifier()) return true;
    const Decl* Key = primaryTemplateMethod(D)->getCanonicalDecl();
    declaredThroughPastingMacro(D, Key);
    handle(D->getLocation(), Key, D->getName());
    return true;
  }

  // ---- types and namespaces: declarations ----
  bool VisitTagDecl(TagDecl* D) {
    if (D->isImplicit() || !D->getIdentifier()) return true;
    handle(D->getLocation(), typeKey(D), D->getName());
    return true;
  }
  bool VisitTypedefNameDecl(TypedefNameDecl* D) {
    if (D->isImplicit() || !D->getIdentifier()) return true;
    handle(D->getLocation(), D->getCanonicalDecl(), D->getName());
    return true;
  }
  bool VisitNamespaceDecl(NamespaceDecl* D) {
    const Decl* Key = namespaceKey(D);
    if (!Key) return true;
    handle(D->getLocation(), Key, D->getName());
    if (Mode == ApplyMode::Rewrite) rewriteNamespaceComment(D, Key);
    return true;
  }
  bool VisitNamespaceAliasDecl(NamespaceAliasDecl* D) {
    handle(D->getAliasLoc(), D->getCanonicalDecl(), D->getName());
    if (const NamedDecl* T = D->getAliasedNamespace())
      handle(D->getTargetNameLoc(), namespaceKey(T), T->getName());
    return true;
  }
  bool VisitUsingDirectiveDecl(UsingDirectiveDecl* D) {
    if (const NamedDecl* T = D->getNominatedNamespaceAsWritten())
      handle(D->getIdentLocation(), namespaceKey(T), T->getName());
    return true;
  }
  // `using ns::Type;` names the type once, at the declaration's own name.
  // (For a member, a using-declaration is deliberately left unaccounted so
  // the spelling audit declines the rename -- see VisitNamedDecl.)
  bool VisitUsingDecl(UsingDecl* D) {
    for (const UsingShadowDecl* S : D->shadows()) {
      const Decl* Key = typeLikeKey(S->getTargetDecl());
      if (!Key) continue;
      handle(D->getLocation(), Key, S->getTargetDecl()->getName());
      break;
    }
    return true;
  }
  // A constructor's name is the class's; the destructor's and a conversion
  // function's names carry a TypeLoc that the type-loc visitors reach.
  bool VisitCXXConstructorDecl(CXXConstructorDecl* D) {
    if (D->isImplicit()) return true;
    const CXXRecordDecl* Parent = D->getParent();
    if (!Parent || !Parent->getIdentifier()) return true;
    handle(D->getLocation(), typeKey(Parent), Parent->getName());
    return true;
  }
  bool VisitCXXDeductionGuideDecl(CXXDeductionGuideDecl* D) {
    if (D->isImplicit()) return true;
    if (const TemplateDecl* T = D->getDeducedTemplate())
      handle(D->getLocation(), templateKey(T), T->getName());
    return true;
  }
  // ---- types and namespaces: uses ----
  bool VisitTagTypeLoc(TagTypeLoc TL) {
    const TagDecl* D = TL.getDecl();
    if (!D || !D->getIdentifier()) return true;
    handle(TL.getNameLoc(), typeKey(D), D->getName(), isUnqualifiedType(TL));
    return true;
  }
  // The qualifier components that name a namespace (`ns::x`), a namespace
  // alias, or -- inside a template -- a dependent name.  Type components are
  // TypeLocs the base traversal visits.
  bool TraverseNestedNameSpecifierLoc(NestedNameSpecifierLoc NNS) {
    using Base = RecursiveASTVisitor<ApplyRenamesVisitor>;
    for (NestedNameSpecifierLoc L = NNS; L; L = L.getPrefix()) {
      const NestedNameSpecifier* S = L.getNestedNameSpecifier();
      if (!S) break;
      switch (S->getKind()) {
        case NestedNameSpecifier::Namespace:
          if (const NamespaceDecl* N = S->getAsNamespace())
            handle(L.getLocalBeginLoc(), namespaceKey(N), N->getName());
          break;
        case NestedNameSpecifier::NamespaceAlias:
          if (const NamespaceAliasDecl* A = S->getAsNamespaceAlias())
            handle(L.getLocalBeginLoc(), A->getCanonicalDecl(), A->getName());
          break;
        case NestedNameSpecifier::Identifier:
          if (const IdentifierInfo* II = S->getAsIdentifier())
            applyDependentToken(L.getLocalBeginLoc(), II->getName());
          break;
        default:
          break;
      }
    }
    return Base::TraverseNestedNameSpecifierLoc(NNS);
  }
  // A template used as a template template argument (`Wrap<Vec>`).
  bool TraverseTemplateArgumentLoc(const TemplateArgumentLoc& AL) {
    using Base = RecursiveASTVisitor<ApplyRenamesVisitor>;
    const TemplateArgument& A = AL.getArgument();
    if (A.getKind() == TemplateArgument::Template ||
        A.getKind() == TemplateArgument::TemplateExpansion) {
      if (const TemplateDecl* TD =
              A.getAsTemplateOrTemplatePattern().getAsTemplateDecl())
        handle(AL.getTemplateNameLoc(), templateKey(TD), TD->getName(),
               !AL.getTemplateQualifierLoc().hasQualifier());
    }
    return Base::TraverseTemplateArgumentLoc(AL);
  }
  // `typename T::Inner`: which type it names is known only per instantiation,
  // so it is rewritten from the cross-TU resolutions like `x.val`.
  bool VisitDependentNameTypeLoc(DependentNameTypeLoc TL) {
    if (const IdentifierInfo* II = TL.getTypePtr()->getIdentifier())
      applyDependentToken(TL.getNameLoc(), II->getName());
    return true;
  }

  bool VisitDeclRefExpr(DeclRefExpr* E) {
    if (Mode == ApplyMode::Scan && !E->getQualifier())
      checkCaptureOfName(E->getDecl(), E->getLocation());
    const Decl* Key = nullptr;
    StringRef OldName;
    if (const auto* VD = dyn_cast<VarDecl>(E->getDecl())) {
      Key = VD->isStaticDataMember()
                ? primaryTemplateStaticMember(VD)->getCanonicalDecl()
                : VD->getCanonicalDecl();
      OldName = VD->getName();
    } else if (const auto* FD = dyn_cast<FieldDecl>(E->getDecl())) {
      Key = primaryTemplateMember(FD);
      OldName = FD->getName();
    } else if (const auto* MD = dyn_cast<CXXMethodDecl>(E->getDecl())) {
      // Unqualified calls to static member functions and pointers to member
      // functions (e.g. `S::count`, `&S::get`).  Coroutine desugaring can
      // leave references to methods without a simple identifier (conversion
      // operators, lambda `operator()`); getName() asserts on those.
      if (!MD->getDeclName().isIdentifier()) return true;
      Key = primaryTemplateMethod(MD)->getCanonicalDecl();
      OldName = MD->getName();
    }
    handle(E->getLocation(), Key, OldName,
           /*Unqualified=*/E->getQualifier() == nullptr);
    return true;
  }

  bool VisitMemberExpr(MemberExpr* E) {
    if (Mode == ApplyMode::Scan && E->getQualifier() == nullptr &&
        E->getMemberDecl()->getDeclName().isIdentifier()) {
      const Expr* B = peelAnonymousMemberBase(E->getBase())->IgnoreImpCasts();
      const auto* T = dyn_cast<CXXThisExpr>(B);
      if (T != nullptr && T->isImplicit())
        checkCaptureOfName(E->getMemberDecl(), E->getMemberLoc());
      else
        checkCaptureThrough(B->getType(), E->isArrow(), E->getMemberDecl(),
                            E->getMemberLoc());
    }
    const Decl* Key = nullptr;
    if (const auto* FD = dyn_cast<FieldDecl>(E->getMemberDecl()))
      Key = primaryTemplateMember(FD);
    else if (const auto* VD = dyn_cast<VarDecl>(E->getMemberDecl()))
      Key = primaryTemplateStaticMember(VD)->getCanonicalDecl();
    else if (const auto* MD = dyn_cast<CXXMethodDecl>(E->getMemberDecl()))
      // Member function calls: `obj.get()`, `ptr->get()`, implicit `this`.
      Key = primaryTemplateMethod(MD)->getCanonicalDecl();
    if (!Key || !E->getMemberDecl()->getDeclName().isIdentifier()) return true;
    if (Mode == ApplyMode::Scan && Vetoes) {
      auto It = Renames.find(Key);
      if (It != Renames.end()) {
        if (const NamedDecl* Hider = renameWouldBeHiddenAt(E, It->second)) {
          std::string Reason = "'" + It->second + "' would be hidden by " +
                               Hider->getQualifiedNameAsString();
          const PresumedLoc PL = SM.getPresumedLoc(Hider->getLocation());
          if (PL.isValid())
            Reason += " (" + relativizeToCwd(PL.getFilename()) + ":" +
                      std::to_string(PL.getLine()) + ") at this use";
          veto(Key, E->getMemberDecl()->getName(), It->second, Reason);
        }
      }
    }
    // `m` alone is an implicit `this->m`, and unqualified lookup finds it -- a
    // local of the new name would capture it.  Anything with a base or a
    // qualifier written out (`this->m`, `obj.m`, `Base::m`) cannot be captured.
    // A member of an anonymous union sits behind an implicit access on the
    // unnamed field, which is peeled first (see peelAnonymousMemberBase).
    const Expr* Base = peelAnonymousMemberBase(E->getBase())->IgnoreImpCasts();
    const auto* This = dyn_cast<CXXThisExpr>(Base);
    const bool Unqualified =
        This != nullptr && This->isImplicit() && E->getQualifier() == nullptr;
    handle(E->getMemberLoc(), Key, E->getMemberDecl()->getName(), Unqualified);
    return true;
  }

  // Constructor mem-initializers (e.g. `S() : val_(0)`).  These are not visited
  // via VisitMemberExpr because CXXCtorInitializer is not a Stmt/Decl.
  bool TraverseConstructorInitializer(CXXCtorInitializer* Init) {
    if (Init && Init->isAnyMemberInitializer()) {
      if (const FieldDecl* FD = Init->getAnyMember())
        handle(Init->getMemberLocation(), primaryTemplateMember(FD),
               FD->getName());
    }
    return RecursiveASTVisitor<
        ApplyRenamesVisitor>::TraverseConstructorInitializer(Init);
  }

  // Designated initializers (e.g. `S s{.val_ = 0}`).  The field name lives in
  // the designator of a DesignatedInitExpr, not in a MemberExpr.
  bool VisitDesignatedInitExpr(DesignatedInitExpr* E) {
    for (const DesignatedInitExpr::Designator& D : E->designators()) {
      if (!D.isFieldDesignator()) continue;
      if (const FieldDecl* FD = D.getFieldDecl())
        handle(D.getFieldLoc(), primaryTemplateMember(FD), FD->getName());
    }
    return true;
  }

  // offsetof(T, member): the member name is a component of an OffsetOfExpr, not
  // a MemberExpr, so no other visitor sees it.  `offsetof` is a macro and the
  // name is one of its arguments, spelled at the call site, so it rewrites like
  // any other reference.  Clang models this completely (OffsetOfNode::getField
  // and a source range over the identifier); the gap was purely ours.
  bool VisitOffsetOfExpr(OffsetOfExpr* E) {
    for (unsigned I = 0; I < E->getNumComponents(); ++I) {
      const OffsetOfNode& N = E->getComponent(I);
      if (N.getKind() == OffsetOfNode::Field) {
        const FieldDecl* FD = N.getField();
        handle(N.getEndLoc(), primaryTemplateMember(FD), FD->getName());
      } else if (N.getKind() == OffsetOfNode::Identifier &&
                 Mode == ApplyMode::Scan && Vetoes) {
        // offsetof on a dependent type: which member the identifier names is
        // known only in an instantiation, and the rewrite pass never walks
        // those, so it could not be rewritten.  Decline the name.
        markSeen(N.getEndLoc());
        if (const IdentifierInfo* II = N.getFieldName())
          vetoByName(Vetoes, Conflicts, ByOldName, SM, II->getName(),
                     "named in offsetof on a dependent type");
      }
    }
    return true;
  }

  // Every declaration's own name is a spelling the audit below must not flag,
  // whatever kind of declaration it is -- a free function or an enumerator
  // that happens to share a member's name is not a use of the member.  A
  // using-declaration is deliberately left out: `using Base::x_;` spells a
  // member the tool does not rewrite, so its token must stay unaccounted for
  // and decline the rename.
  bool VisitNamedDecl(NamedDecl* D) {
    if (Mode == ApplyMode::Scan &&
        !isa<UsingDecl, UsingShadowDecl, UnresolvedUsingValueDecl,
             UnresolvedUsingTypenameDecl>(D))
      markSeen(D->getLocation());
    return true;
  }

  // Scan mode only, after the traversal.  Every identifier in the main file
  // that spells a name being renamed must have been reached through some
  // reference the visitor understands.  One that was not is a use of a kind
  // the tool does not know -- a using-declaration, an unresolved overload set
  // inside a template, a name in a #if branch this build does not take, an
  // unexpanded macro body -- and the rename would leave it behind.  So the name
  // is declined.  This is the generic backstop for the reference kinds nobody
  // has thought of yet: it would have caught OffsetOfExpr without anyone
  // knowing it existed.  Comments and string literals are not identifiers to
  // the raw lexer, so they cost nothing; a name spelled in a comment does not
  // decline anything.
  void auditSpellings(const LangOptions& LangOpts) {
    if (Mode != ApplyMode::Scan || !Vetoes || ByOldName.empty()) return;
    // Every file of this TU that the rewrite pass may edit: the main file, and
    // in Emit mode every owned file too, because a header has no action of its
    // own there and the TUs that include it are the only chance to audit it.
    // fileinfo_begin/end enumerates exactly the files this TU read,
    // so a path in the owned set that this TU never included costs nothing.
    // Sorted by FileID, so the vetoes a TU records do not depend on the
    // iteration order of a DenseMap.
    std::vector<FileID> Files;
    for (auto It = SM.fileinfo_begin(), End = SM.fileinfo_end(); It != End;
         ++It) {
      const FileID FID = SM.translateFile(It->first);
      if (FID.isInvalid()) continue;
      // Only Emit mode looks past the main file, for the same reason owns()
      // does: there a header has no action of its own.  A direct run parses
      // every owned file as some TU's main file, so widening would only
      // duplicate the work and change which of several true reasons is the
      // one recorded first.
      if (FID != SM.getMainFileID() &&
          (!Edits ||
           !isRewritableFile(SM.getLocForStartOfFile(FID), SM, CollectFrom)))
        continue;
      Files.push_back(FID);
    }
    std::sort(Files.begin(), Files.end(), [](FileID A, FileID B) {
      return A.getHashValue() < B.getHashValue();
    });
    for (FileID FID : Files) auditOneFile(FID, LangOpts);
  }

 private:
  void auditOneFile(FileID FID, const LangOptions& LangOpts) {
    Lexer Lex(FID, SM.getBufferOrFake(FID), SM, LangOpts);
    Token Tok;
    while (true) {
      Lex.LexFromRawLexer(Tok);
      if (Tok.is(tok::eof)) break;
      if (Tok.isNot(tok::raw_identifier)) continue;
      const StringRef Text = Tok.getRawIdentifier();
      if (ByOldName.count(Text.str()) == 0) continue;
      const std::pair<FileID, unsigned> At =
          SM.getDecomposedLoc(Tok.getLocation());
      if (Seen.count(At) > 0) continue;
      // An argument the macro only pastes or stringizes never reaches the
      // parser as itself; nothing can refer to the name here.
      if (Consumed && Consumed->Tokens.count(At) > 0) continue;
      std::string Reason =
          "spelled where no reference the tool understands "
          "accounts for it";
      const PresumedLoc PL = SM.getPresumedLoc(Tok.getLocation());
      if (PL.isValid())
        Reason += ": " + relativizeToCwd(PL.getFilename()) + ":" +
                  std::to_string(PL.getLine());
      vetoByName(Vetoes, Conflicts, ByOldName, SM, Text, Reason);
    }
  }

 public:
  // Template-dependent member access (e.g. `x.val` where x is a template
  // parameter).  The member is unresolved in this TU, so we rewrite it from the
  // cross-TU resolution recorded by the TUs that instantiate the template.
  // Only the token in its own main file is rewritten (as for every other site),
  // which -- combined with headers-last ordering -- keeps each file written
  // once.  There is no declaration to veto here: which member the token names
  // is exactly what this TU does not know, and DependentResolutions carries its
  // own veto for that.
  bool VisitCXXDependentScopeMemberExpr(CXXDependentScopeMemberExpr* E) {
    if (Mode == ApplyMode::Scan) {
      markSeen(E->getMemberLoc());
      return true;
    }
    // Emit mode defers dependent-token edits to the aggregation phase (which
    // has the full cross-TU resolution picture); here we only serialize the
    // resolutions this TU observed.
    if (!DepRes || Edits) return true;
    SourceLocation Loc = E->getMemberLoc();
    if (!owns(Loc)) return true;
    auto Key = ownedKey(Loc, SM, CollectFrom);
    if (!Key) return true;
    auto It = DepRes->find(*Key);
    if (It == DepRes->end() || It->second.Vetoed || !It->second.HasName)
      return true;
    const IdentifierInfo* II = E->getMember().getAsIdentifierInfo();
    if (!II) return true;
    renameAt(Loc, nullptr, II->getName(), It->second.NewName);
    return true;
  }

  // The qualified-name counterpart (`Helper<T>::member`).  Same deal: rewritten
  // from the resolution the instantiating TUs recorded, in its own main file.
  bool VisitDependentScopeDeclRefExpr(DependentScopeDeclRefExpr* E) {
    if (Mode == ApplyMode::Scan) {
      markSeen(E->getLocation());
      return true;
    }
    if (!DepRes || Edits) return true;
    SourceLocation Loc = E->getLocation();
    if (!owns(Loc)) return true;
    auto Key = ownedKey(Loc, SM, CollectFrom);
    if (!Key) return true;
    auto It = DepRes->find(*Key);
    if (It == DepRes->end() || It->second.Vetoed || !It->second.HasName)
      return true;
    const IdentifierInfo* II = E->getDeclName().getAsIdentifierInfo();
    if (!II) return true;
    renameAt(Loc, nullptr, II->getName(), It->second.NewName);
    return true;
  }

 private:
  // One reference site, in whichever mode this pass is running.
  // \p Unqualified says the reference finds the member by unqualified name
  // lookup, so a local of the new name would capture it.  False for anything
  // written with an explicit qualifier or base (`this->m`, `obj.m`, `S::m`),
  // for declarations, and for the member name in a mem-initializer or a field
  // designator -- those are looked up in the class, never in the local scope.
  void handle(SourceLocation Loc, const Decl* Key, StringRef OldName,
              bool Unqualified = false) {
    markSeen(Loc);
    if (!Key || Loc.isInvalid()) return;
    auto It = Renames.find(Key);
    if (It == Renames.end()) {
      // Not in the map.  The scan pass walks template instantiations, so this
      // is where a member that primaryTemplateMember() failed to map back to
      // its pattern shows up: its pattern is renamed, and this use of it would
      // not be.  If a declaration of the same name is being renamed, decline
      // the name rather than trust the mapping.
      if (Mode == ApplyMode::Scan && Vetoes && !OldName.empty() &&
          isClassMemberDecl(Key) && isInTemplateInstantiation(Key) &&
          ByOldName.count(OldName.str()) > 0)
        vetoByName(Vetoes, Conflicts, ByOldName, SM, OldName,
                   "a use in a template instantiation resolves to a member "
                   "that could not be mapped to its declaration" +
                       unmappedContext(Key, Loc));
      return;
    }
    if (Mode == ApplyMode::Scan) {
      scan(Loc, Key, OldName, It->second, Unqualified);
      return;
    }
    if (!owns(Loc)) return;
    renameAt(Loc, Key, OldName, It->second);
  }

  // Two ways a reference can make a rename unsafe.
  void scan(SourceLocation Loc, const Decl* Key, StringRef OldName,
            const std::string& NewName, bool Unqualified) {
    if (!Vetoes) return;
    // (a) No rewritable spelling, so the reference would keep the old name.
    // This deliberately ignores file ownership: a macro in a header we do not
    // own that names one of our members is just as fatal, and just as
    // unrewritable.
    if (!rewriteLoc(Loc).isValid()) {
      SourceLocation Spelling = SM.getSpellingLoc(Loc);
      std::string Reason;
      if (!SM.getFileEntryForID(SM.getFileID(Spelling))) {
        Reason = "the name is formed by token pasting";
      } else {
        PresumedLoc PLoc = SM.getPresumedLoc(Spelling);
        Reason = "referenced from a macro body";
        if (PLoc.isValid())
          Reason += " at " + relativizeToCwd(PLoc.getFilename()) + ":" +
                    std::to_string(PLoc.getLine());
      }
      veto(Key, OldName, NewName, Reason);
      return;
    }
    // (c) The token is spelled in a file no invocation will rewrite: not this
    // TU's main file and not one of the owned files.  The declaration would be
    // renamed and this use left behind.  Two shapes land here: a textual header
    // (an .inc in textual_hdrs) that the build never lists as a source, and a
    // standard-library or third-party template instantiated with one of our
    // types that calls one of our members by name -- std::back_inserter on our
    // container spells push_back inside <iterator>.  Both are references the
    // tool can see and cannot rewrite, which is exactly what a veto is for.
    if (!ownedKey(Loc, SM, CollectFrom)) {
      const PresumedLoc PLoc = SM.getPresumedLoc(rewriteLoc(Loc));
      std::string Reason = "referenced from a file that is not being formatted";
      if (PLoc.isValid())
        Reason += ": " + relativizeToCwd(PLoc.getFilename()) + ":" +
                  std::to_string(PLoc.getLine());
      veto(Key, OldName, NewName, Reason);
      return;
    }
    // (b) The token can be rewritten, but would no longer name the member: it
    // is found by unqualified lookup and a local or parameter of the new name
    // is in scope here, so the rewrite silently rebinds the use.  googletest's
    // OnCallSpec::action_ -> action, inside WillByDefault(const Action<F>&
    // action), turns `action_ = action` into the self-assignment `action =
    // action`.  Every enclosing function is checked, not just the innermost,
    // since a lambda body can name either.
    if (!Unqualified) return;
    for (const std::set<std::string>& Frame : LocalNames) {
      if (Frame.find(NewName) == Frame.end()) continue;
      veto(Key, OldName, NewName,
           "'" + NewName + "' is a local or parameter where it is used");
      return;
    }
  }

  void veto(const Decl* Key, StringRef OldName, const std::string& NewName,
            const std::string& Reason) {
    if (!addRenameVeto(Vetoes, Key, SM, OldName, Reason)) return;
    if (!Conflicts) return;
    const PresumedLoc PL =
        SM.getPresumedLoc(cast<NamedDecl>(Key)->getLocation());
    Conflicts->push_back(RenameConflict{
        PL.isValid() ? PL.getFilename() : "", PL.isValid() ? PL.getLine() : 0,
        PL.isValid() ? PL.getColumn() : 0, OldName.str(), NewName, Reason});
  }

  // A declaration spelled as a macro *argument* renames fine -- unless the
  // macro also pastes (`##`), because then the argument's spelling is part of
  // other identifiers the macro forms.  gmock's ACTION_P3(Plus, foo, bar, baz)
  // declares a member `foo` and a typedef `foo##_type`; renaming the member to
  // `foo_` makes the typedef `foo__type`, and the action body -- which gmock
  // documents as allowed to spell `foo_type` -- no longer compiles.  Those
  // pasted names are never references the tool can see, so the declaration is
  // declined outright when any macro on its expansion chain contains `##`.
  void declaredThroughPastingMacro(const NamedDecl* D, const Decl* Key) {
    if (Mode != ApplyMode::Scan || !Vetoes || !PP || !Key) return;
    SourceLocation Loc = D->getLocation();
    if (!Loc.isMacroID() || !D->getDeclName().isIdentifier()) return;
    auto It = Renames.find(Key);
    if (It == Renames.end()) return;
    // The preprocessor's own record of which arguments got pasted, at any
    // nesting depth.  The chain walk below only sees the macros the
    // declaration's *own* token went through; gmock's MOCK_METHOD spells the
    // method plainly in GMOCK_INTERNAL_MOCK_METHOD_IMPL and hands the same
    // argument to GMOCK_MOCKER_, which is where gmock_##Method is formed.
    if (Consumed) {
      const SourceLocation Spelling = rewriteLoc(Loc);
      if (Spelling.isValid() &&
          Consumed->Pasted.count(SM.getDecomposedLoc(Spelling)) > 0) {
        veto(Key, D->getName(), It->second,
             "declared through a macro argument that is pasted with ##; the "
             "spelling is part of other names the macro forms");
        return;
      }
    }
    for (unsigned Guard = 0; Loc.isMacroID() && Guard < 64; ++Guard) {
      const StringRef Name =
          Lexer::getImmediateMacroName(Loc, SM, PP->getLangOpts());
      if (!Name.empty()) {
        if (const MacroInfo* MI =
                PP->getMacroInfo(PP->getIdentifierInfo(Name))) {
          for (const Token& T : MI->tokens()) {
            if (!T.is(tok::hashhash)) continue;
            veto(Key, D->getName(), It->second,
                 "declared through an argument of macro " + Name.str() +
                     ", which pastes tokens with ##; the spelling may be part "
                     "of other names the macro forms");
            return;
          }
        }
      }
      Loc = SM.getImmediateExpansionRange(Loc).getBegin();
    }
  }

  // Diagnostic detail for the backstop above: which class the unmapped member
  // belongs to and where the use is, so a new unmapped shape can be reduced.
  std::string unmappedContext(const Decl* Key, SourceLocation Loc) const {
    std::string Out;
    if (const auto* ND = dyn_cast<NamedDecl>(Key))
      if (const auto* RD = dyn_cast<CXXRecordDecl>(ND->getDeclContext()))
        Out += " (member of " + RD->getQualifiedNameAsString() + ")";
    const PresumedLoc PL = SM.getPresumedLoc(rewriteLoc(Loc));
    if (PL.isValid())
      Out += " at " + relativizeToCwd(PL.getFilename()) + ":" +
             std::to_string(PL.getLine());
    return Out;
  }

  // Whether a type loc is written without a qualifier or an elaborated-type
  // keyword (see TraverseElaboratedTypeLoc); only the scan pass asks.
  bool isUnqualifiedType(TypeLoc TL) const {
    return Mode == ApplyMode::Scan &&
           QualifiedNamedLocs.count(TL.getOpaqueData()) == 0;
  }

  // A dependent token of any kind: seen by the scan, rewritten from the
  // cross-TU resolution in its own main file (see the member-access variant
  // in VisitCXXDependentScopeMemberExpr, which this mirrors).
  void applyDependentToken(SourceLocation Loc, StringRef Name) {
    if (Mode == ApplyMode::Scan) {
      markSeen(Loc);
      return;
    }
    if (!DepRes || Edits || !owns(Loc)) return;
    auto Key = ownedKey(Loc, SM, CollectFrom);
    if (!Key) return;
    auto It = DepRes->find(*Key);
    if (It == DepRes->end() || It->second.Vetoed || !It->second.HasName) return;
    renameAt(Loc, nullptr, Name, It->second.NewName);
  }

  // The `}  // namespace foo` comment a namespace definition closes with
  // (`}  // namespace a::b` for a nested-namespace-definition): the component
  // spelling this namespace's old name is rewritten along with it.  Only a
  // line comment directly after the brace, and only the name run after the
  // word `namespace`; anything else is left as written.
  void rewriteNamespaceComment(const NamespaceDecl* D, const Decl* Key) {
    auto It = Renames.find(Key);
    if (It == Renames.end()) return;
    const SourceLocation RB = D->getRBraceLoc();
    if (RB.isInvalid() || RB.isMacroID() || !owns(RB)) return;
    bool Invalid = false;
    const char* Data = SM.getCharacterData(RB, &Invalid);
    if (Invalid || !Data || *Data != '}') return;
    const char* P = Data + 1;
    const auto skipBlanks = [&] {
      while (*P == ' ' || *P == '\t') ++P;
    };
    skipBlanks();
    if (P[0] != '/' || P[1] != '/') return;
    P += 2;
    skipBlanks();
    if (!StringRef(P).starts_with("namespace")) return;
    P += 9;
    if (*P != ' ' && *P != '\t') return;
    skipBlanks();
    const char* Start = P;
    while (std::isalnum(static_cast<unsigned char>(*P)) || *P == '_' ||
           *P == ':')
      ++P;
    const StringRef Run(Start, P - Start);
    const StringRef Old = cast<NamedDecl>(Key)->getName();
    size_t Pos = 0;
    while (Pos <= Run.size()) {
      const size_t E = Run.find("::", Pos);
      const StringRef Comp =
          Run.substr(Pos, E == StringRef::npos ? StringRef::npos : E - Pos);
      if (Comp == Old) {
        renameAt(RB.getLocWithOffset((Start - Data) + Pos), Key, Old,
                 It->second);
        return;
      }
      if (E == StringRef::npos) break;
      Pos = E + 2;
    }
  }

  // ---- the capture check (see contextKey above) ----

  // The lookup path from the current site, innermost scope first.
  llvm::SmallVector<const DeclContext*, 8> siteChain() const {
    llvm::SmallVector<const DeclContext*, 8> Chain;
    if (ContextStack.empty()) return Chain;
    for (const DeclContext* DC = ContextStack.back(); DC; DC = DC->getParent())
      Chain.push_back(DC);
    return Chain;
  }

  // An unqualified name at the current site that today means \p Target.
  void checkCaptureOfName(const NamedDecl* Target, SourceLocation UseLoc) {
    if (Mode != ApplyMode::Scan || !Target || ByNewName.empty()) return;
    if (!Target->getDeclName().isIdentifier()) return;
    checkCapture(Target->getName(), Target, siteChain(), UseLoc);
  }

  // A member access `obj.name` / `ptr->name` on an object of type \p T: lookup
  // starts at the object's class, not at the site.
  void checkCaptureThrough(QualType T, bool IsArrow, const NamedDecl* Target,
                           SourceLocation UseLoc) {
    if (Mode != ApplyMode::Scan || !Target || ByNewName.empty()) return;
    if (!Target->getDeclName().isIdentifier()) return;
    if (IsArrow) {
      const auto* PT = T->getAs<PointerType>();
      if (!PT) return;
      T = PT->getPointeeType();
    }
    const CXXRecordDecl* From = T->getAsCXXRecordDecl();
    if (!From) return;
    const llvm::SmallVector<const DeclContext*, 8> Chain{From};
    checkCapture(Target->getName(), Target, Chain, UseLoc);
  }

  // A type spelled by \p TL, unless TraverseElaboratedTypeLoc excused it.
  void checkCaptureOfType(TypeLoc TL, const NamedDecl* D) {
    if (Mode != ApplyMode::Scan || !D || ByNewName.empty()) return;
    if (QualifiedNamedLocs.count(TL.getOpaqueData()) > 0) return;
    checkCaptureOfName(D, TL.getBeginLoc());
  }

  // \p Name is looked up from \p Chain (innermost first) and today finds
  // \p Target.  Every rename whose new spelling is \p Name and whose scope the
  // lookup passes through *before* it reaches Target is vetoed.
  void checkCapture(StringRef Name, const NamedDecl* Target,
                    llvm::ArrayRef<const DeclContext*> Chain,
                    SourceLocation UseLoc) {
    if (!Vetoes || Chain.empty()) return;
    auto Range = ByNewName.equal_range(Name.str());
    if (Range.first == Range.second) return;
    const DeclContext* TargetHome = homeScopeOf(Target);
    const auto* TargetVar = dyn_cast<VarDecl>(Target);
    const bool TargetIsLocal = TargetVar && TargetVar->isLocalVarDeclOrParm();
    const auto indexOf = [&](const void* Key) {
      for (size_t I = 0; I < Chain.size(); ++I)
        if (contextKey(Chain[I]) == Key) return I;
      return Chain.size();
    };
    for (auto It = Range.first; It != Range.second; ++It) {
      const Decl* Key = It->second.Key;
      const DeclContext* Home = isClassMemberDecl(Key)
                                    ? lookupHomeOf(cast<NamedDecl>(Key))
                                    : homeScopeOf(Key);
      if (!Home) continue;
      const void* HomeKey = contextKey(Home);
      const bool HomeIsRecord = isa<CXXRecordDecl>(Home);
      // The first scope on the path that the rename would put the name into:
      // Home itself, or a class derived from it.
      size_t Pos = indexOf(HomeKey);
      if (HomeIsRecord && Pos == Chain.size()) {
        for (size_t I = 0; I < Chain.size() && Pos == Chain.size(); ++I) {
          const auto* RD = dyn_cast<CXXRecordDecl>(Chain[I]);
          llvm::SmallPtrSet<const CXXRecordDecl*, 8> Visited;
          if (RD && derivesFrom(RD, HomeKey, Visited)) Pos = I;
        }
      }
      if (Pos == Chain.size()) continue;  // lookup from here never gets there
      // Would what the name means today still be found first?  A local always
      // precedes class scope; anything declared in a scope inside the one the
      // rename lands in precedes it; so does a member of a class between the
      // site and Home on the derivation path (it hides Home's member).  At
      // Home itself the name is collides()'s business.
      if (TargetIsLocal && HomeIsRecord) continue;
      if (TargetHome) {
        if (indexOf(contextKey(TargetHome)) <= Pos) continue;
        if (HomeIsRecord) {
          const auto* RT = dyn_cast<CXXRecordDecl>(TargetHome);
          llvm::SmallPtrSet<const CXXRecordDecl*, 8> Visited;
          if (RT &&
              (contextKey(RT) == HomeKey || derivesFrom(RT, HomeKey, Visited)))
            continue;
        }
      }
      std::string Reason = "'" + It->first + "' is used unqualified";
      if (const auto* Scope = dyn_cast_or_null<NamedDecl>(
              Decl::castFromDeclContext(Chain[Pos])))
        Reason += " in " + Scope->getQualifiedNameAsString();
      const PresumedLoc PL = SM.getPresumedLoc(UseLoc);
      if (PL.isValid())
        Reason += " (" + relativizeToCwd(PL.getFilename()) + ":" +
                  std::to_string(PL.getLine()) + ")";
      Reason += " to mean " + Target->getQualifiedNameAsString() +
                ", which the renamed '" + It->second.Old + "' would hide";
      veto(Key, It->second.Old, It->first, Reason);
    }
  }

  // Records that the scan reached the token spelled at \p Loc (its rewrite
  // location: the spelling for a macro argument), for auditMainFileSpellings.
  void markSeen(SourceLocation Loc) {
    if (Mode != ApplyMode::Scan || InstantiationDepth > 0) return;
    const SourceLocation RL = rewriteLoc(Loc);
    if (RL.isValid()) Seen.insert(SM.getDecomposedLoc(RL));
  }

  auto ownerKey(const Decl* Key) -> std::pair<std::string, unsigned> {
    if (!Key) return {};
    auto It = OwnerKeys.find(Key);
    if (It != OwnerKeys.end()) return It->second;
    return OwnerKeys.emplace(Key, renameOwnerKey(Key, SM)).first->second;
  }

  Rewriter& RW;
  SourceManager& SM;
  const RenameMap& Renames;
  const FileSet& CollectFrom;
  DependentResolutions* DepRes;  // null when the feature is disabled
  LintReport* Report;            // null outside Lint mode
  std::string RuleId;
  EditReport* Edits;  // non-null in Emit mode
  ApplyMode Mode;
  RenameVetoes* Vetoes;        // non-null when all-or-nothing is enabled
  RenameConflicts* Conflicts;  // where a veto is reported
  std::set<std::pair<FileID, unsigned>> Rewritten;
  std::map<const Decl*, std::pair<std::string, unsigned>> OwnerKeys;
  // One frame per enclosing function, innermost last.  Scan mode only.
  std::vector<std::set<std::string>> LocalNames;
  RenamesByOldName ByOldName;                  // Scan mode only
  std::set<std::pair<FileID, unsigned>> Seen;  // Scan mode only
  unsigned InstantiationDepth = 0;             // Scan mode only
  Preprocessor* PP = nullptr;                  // Scan mode only, may be null
  // Scan mode only, for the capture check: the renames by their *new* name,
  // the declaration contexts being traversed (innermost last), and the type
  // locs written with a qualifier or an elaborated-type keyword.
  struct NewNameEntry {
    const Decl* Key;
    std::string Old;
  };
  std::multimap<std::string, NewNameEntry> ByNewName;
  std::vector<const DeclContext*> ContextStack;
  std::set<const void*> QualifiedNamedLocs;
  const ConsumedMacroArgs* Consumed = nullptr;  // Scan mode only, may be null
};

// ---------------------------------------------------------------------------
// Debug tracer — visits every reference to a renamed variable and logs it.
// Used by OutputMode::Debug so users can see, per TU, exactly which sites the
// tool detected and which would actually be rewritten (main-file + non-macro).
// ---------------------------------------------------------------------------

class DebugTraceVisitor : public RecursiveASTVisitor<DebugTraceVisitor> {
 public:
  DebugTraceVisitor(SourceManager& SM, const RenameMap& Renames,
                    llvm::raw_ostream& Out)
      : SM(SM), Renames(Renames), Out(Out) {}

  bool VisitFieldDecl(FieldDecl* D) {
    auto It = Renames.find(D->getCanonicalDecl());
    if (It != Renames.end())
      log("FieldDecl ", D->getLocation(), D->getName(), It->second);
    return true;
  }
  bool VisitVarDecl(VarDecl* D) {
    const Decl* Key = D->isStaticDataMember()
                          ? primaryTemplateStaticMember(D)->getCanonicalDecl()
                          : D->getCanonicalDecl();
    auto It = Renames.find(Key);
    if (It != Renames.end())
      log("VarDecl   ", D->getLocation(), D->getName(), It->second);
    return true;
  }
  bool VisitCXXMethodDecl(CXXMethodDecl* D) {
    auto It = Renames.find(primaryTemplateMethod(D)->getCanonicalDecl());
    if (It != Renames.end())
      log("MethodDecl", D->getLocation(), D->getName(), It->second);
    return true;
  }
  bool VisitDeclRefExpr(DeclRefExpr* E) {
    const Decl* Key = nullptr;
    StringRef OldName;
    if (const auto* VD = dyn_cast<VarDecl>(E->getDecl())) {
      Key = VD->isStaticDataMember()
                ? primaryTemplateStaticMember(VD)->getCanonicalDecl()
                : VD->getCanonicalDecl();
      OldName = VD->getName();
    } else if (const auto* FD = dyn_cast<FieldDecl>(E->getDecl())) {
      Key = primaryTemplateMember(FD);
      OldName = FD->getName();
    } else if (const auto* MD = dyn_cast<CXXMethodDecl>(E->getDecl())) {
      if (!MD->getDeclName().isIdentifier()) return true;
      Key = primaryTemplateMethod(MD)->getCanonicalDecl();
      OldName = MD->getName();
    }
    if (!Key) return true;
    auto It = Renames.find(Key);
    if (It != Renames.end())
      log("DeclRef   ", E->getLocation(), OldName, It->second);
    return true;
  }
  bool VisitMemberExpr(MemberExpr* E) {
    const Decl* Key = nullptr;
    StringRef OldName;
    if (const auto* FD = dyn_cast<FieldDecl>(E->getMemberDecl())) {
      Key = primaryTemplateMember(FD);
      OldName = FD->getName();
    } else if (const auto* VD = dyn_cast<VarDecl>(E->getMemberDecl())) {
      Key = primaryTemplateStaticMember(VD)->getCanonicalDecl();
      OldName = VD->getName();
    } else if (const auto* MD = dyn_cast<CXXMethodDecl>(E->getMemberDecl())) {
      if (!MD->getDeclName().isIdentifier()) return true;
      Key = primaryTemplateMethod(MD)->getCanonicalDecl();
      OldName = MD->getName();
    }
    if (!Key) return true;
    auto It = Renames.find(Key);
    if (It != Renames.end())
      log("MemberExpr", E->getMemberLoc(), OldName, It->second);
    return true;
  }

  bool TraverseConstructorInitializer(CXXCtorInitializer* Init) {
    if (Init && Init->isAnyMemberInitializer()) {
      if (const FieldDecl* FD = Init->getAnyMember()) {
        auto It = Renames.find(primaryTemplateMember(FD));
        if (It != Renames.end())
          log("CtorInit  ", Init->getMemberLocation(), FD->getName(),
              It->second);
      }
    }
    return RecursiveASTVisitor<
        DebugTraceVisitor>::TraverseConstructorInitializer(Init);
  }

  bool VisitDesignatedInitExpr(DesignatedInitExpr* E) {
    for (const DesignatedInitExpr::Designator& D : E->designators()) {
      if (!D.isFieldDesignator()) continue;
      const FieldDecl* FD = D.getFieldDecl();
      if (!FD) continue;
      auto It = Renames.find(primaryTemplateMember(FD));
      if (It != Renames.end())
        log("DesignInit", D.getFieldLoc(), FD->getName(), It->second);
    }
    return true;
  }

  bool VisitOffsetOfExpr(OffsetOfExpr* E) {
    for (unsigned I = 0; I < E->getNumComponents(); ++I) {
      const OffsetOfNode& N = E->getComponent(I);
      if (N.getKind() != OffsetOfNode::Field) continue;
      const FieldDecl* FD = N.getField();
      auto It = Renames.find(primaryTemplateMember(FD));
      if (It != Renames.end())
        log("OffsetOf  ", N.getEndLoc(), FD->getName(), It->second);
    }
    return true;
  }

 private:
  void log(StringRef Kind, SourceLocation Loc, StringRef OldName,
           const std::string& NewName) {
    auto PLoc = SM.getPresumedLoc(Loc);
    const bool isMacro = Loc.isMacroID();
    // Where the applier would rewrite: the token itself, or -- for a macro
    // argument -- the call site that spells it.  Invalid means the name has no
    // spelling of its own (macro body, or ## paste), which vetoes the rename
    // for every site, not just this one.
    const SourceLocation RL = rewriteLocFor(Loc, SM);
    const bool inMain = RL.isValid() && SM.getFileID(RL) == SM.getMainFileID();
    const char* file = PLoc.isValid() ? PLoc.getFilename() : "<invalid>";
    unsigned line = PLoc.isValid() ? PLoc.getLine() : 0;
    unsigned col = PLoc.isValid() ? PLoc.getColumn() : 0;
    Out << "    " << Kind << "  " << OldName << " -> " << NewName << "  at "
        << file << ":" << line << ":" << col
        << "  [main=" << (inMain ? "Y" : "N")
        << " macro=" << (isMacro ? "Y" : "N") << "]";
    if (!RL.isValid())
      Out << "  VETOES_RENAME";
    else if (inMain)
      Out << "  WILL_RENAME";
    Out << "\n";
  }

  SourceManager& SM;
  const RenameMap& Renames;
  llvm::raw_ostream& Out;
};

