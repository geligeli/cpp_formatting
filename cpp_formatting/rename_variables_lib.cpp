// Only ordinary named member functions can be renamed: constructors and
// destructors take the class name, conversion functions and overloaded
// operators have no identifier of their own that renameToStyle could rewrite
// without breaking the syntax.
static bool isRenamableMethod(const CXXMethodDecl* MD) {
  if (isa<CXXConstructorDecl, CXXDestructorDecl, CXXConversionDecl>(MD))
    return false;
  return MD->getOverloadedOperator() == OO_None;
}

// Member functions the core language or the standard library calls on a user's
// type *without spelling the name anywhere in the user's code*: a range-for
// calls begin()/end(), a structured binding calls get<I>(), std::lock_guard
// calls lock()/unlock(), std::back_inserter calls push_back(), the coroutine
// machinery calls await_ready() and friends, allocator_traits calls allocate().
// Renaming one of these is a *complete* rename -- every spelled reference is
// rewritten -- that still does not compile, because the reference that matters
// is generated by the compiler or lives in a system header.  No amount of
// reference-finding can see it, so the names are declined by fiat.
static bool isProtocolMethodName(llvm::StringRef Name) {
  static const llvm::StringSet<> kNames = {
      // range-for, std::begin/end/size/empty/data, ranges, span
      "begin",
      "end",
      "cbegin",
      "cend",
      "rbegin",
      "rend",
      "crbegin",
      "crend",
      "size",
      "ssize",
      "empty",
      "data",
      // std::back_inserter / front_inserter / inserter
      "push_back",
      "push_front",
      "insert",
      // structured bindings on tuple-like types; std::swap-adjacent idioms
      "get",
      "swap",
      // BasicLockable / Lockable / SharedLockable / TimedLockable
      "lock",
      "unlock",
      "try_lock",
      "lock_shared",
      "unlock_shared",
      "try_lock_shared",
      "try_lock_for",
      "try_lock_until",
      // coroutine promise / awaitable protocol
      "await_ready",
      "await_suspend",
      "await_resume",
      "await_transform",
      "get_return_object",
      "get_return_object_on_allocation_failure",
      "initial_suspend",
      "final_suspend",
      "return_void",
      "return_value",
      "yield_value",
      "unhandled_exception",
      // allocator protocol, reached through std::allocator_traits
      "allocate",
      "deallocate",
      "construct",
      "destroy",
      "max_size",
      "select_on_container_copy_construction",
  };
  return kNames.count(Name) > 0;
}

// The one data-member protocol name: the type-trait convention.
// std::conjunction and std::bool_constant read `B::value` on user traits, so a
// static data member of that name is part of an interface the standard library
// consumes.
static bool isProtocolStaticMemberName(const NamedDecl* D) {
  const auto* VD = dyn_cast<VarDecl>(D);
  return VD && VD->isStaticDataMember() && VD->getName() == "value";
}

bool matchesScope(const NamedDecl* D, VariableScope Scope) {
  switch (Scope) {
    case VariableScope::Member:
      if (isa<FieldDecl>(D)) return true;
      if (const auto* VD = dyn_cast<VarDecl>(D))
        return VD->isStaticDataMember();
      return false;
    case VariableScope::Local: {
      const auto* VD = dyn_cast<VarDecl>(D);
      return VD && VD->isLocalVarDeclOrParm();
    }
    case VariableScope::Global: {
      const auto* VD = dyn_cast<VarDecl>(D);
      return VD && !VD->isLocalVarDeclOrParm() && !VD->isStaticDataMember();
    }
    case VariableScope::StaticMember: {
      const auto* VD = dyn_cast<VarDecl>(D);
      return VD && VD->isStaticDataMember();
    }
    case VariableScope::ConstMember: {
      const auto* VD = dyn_cast<VarDecl>(D);
      return VD && VD->isStaticDataMember() &&
             (VD->isConstexpr() || VD->getType().isConstQualified());
    }
    case VariableScope::StaticGlobal: {
      const auto* VD = dyn_cast<VarDecl>(D);
      if (!VD || VD->isLocalVarDeclOrParm() || VD->isStaticDataMember())
        return false;
      return VD->getStorageClass() == SC_Static;
    }
    case VariableScope::ConstGlobal: {
      const auto* VD = dyn_cast<VarDecl>(D);
      if (!VD || VD->isLocalVarDeclOrParm() || VD->isStaticDataMember())
        return false;
      return VD->isConstexpr() || VD->getType().isConstQualified();
    }
    case VariableScope::Method: {
      const auto* MD = dyn_cast<CXXMethodDecl>(D);
      return MD && isRenamableMethod(MD);
    }
  }
  return false;
}

