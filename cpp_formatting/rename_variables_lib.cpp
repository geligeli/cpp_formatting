// Template instantiation helpers
// ---------------------------------------------------------------------------

// The record \p RD was instantiated from, or null if it is not an
// instantiation.  Instantiated records come in two shapes and only the first is
// a ClassTemplateSpecializationDecl:
//
//   Outer<int>            -- a specialization; its pattern is the primary
//                            template's CXXRecordDecl.
//   Outer<int>::Inner     -- a class *nested* in a class template is an
//                            ordinary CXXRecordDecl whose pattern comes from
//                            getInstantiatedFromMemberClass().
//
// Missing the second shape meant members of a nested class never mapped back to
// the pattern the rename map is keyed by: the declaration was renamed (it is
// collected from the pattern) while every use in an instantiation was skipped,
// and dependent uses were vetoed for binding to a member "not being renamed".
static const CXXRecordDecl* instantiationPattern(const CXXRecordDecl* RD) {
  if (const auto* Spec = dyn_cast<ClassTemplateSpecializationDecl>(RD)) {
    // An explicit specialization is not an instantiation: its members are
    // written out, and are their own pattern.  Mapping them anywhere would be
    // matching two unrelated member lists by position.
    const TemplateSpecializationKind Kind =
        Spec->getTemplateSpecializationKind();
    if (Kind == TSK_Undeclared || Kind == TSK_ExplicitSpecialization)
      return nullptr;
    // An instantiation of a *partial* specialization must map back to that
    // specialization's own members, not the primary template's: they are
    // different classes with different member lists, so matching by index
    // across them rebinds a use to an unrelated member.
    auto From = Spec->getSpecializedTemplateOrPartial();
    if (auto* Partial =
            dyn_cast<ClassTemplatePartialSpecializationDecl*>(From)) {
      // A partial specialization of a *member* template, instantiated inside
      // an enclosing instantiation, is itself a copy; walk to the one written.
      while (ClassTemplatePartialSpecializationDecl* M =
                 Partial->getInstantiatedFromMember())
        Partial = M;
      return Partial;
    }
    // Likewise for the template itself: `Outer<int>::Impl<R>` is a member
    // template that Clang instantiated along with Outer<int>, and only the
    // ClassTemplateDecl -- not its templated record -- points back at the
    // member template written in Outer<T>.  gmock's
    // ReturnRefOfCopyAction<T>::Impl<R> is the shape; without this hop every
    // field of Impl looked unmapped and was declined.
    ClassTemplateDecl* Tmpl = cast<ClassTemplateDecl*>(From);
    while (ClassTemplateDecl* M = Tmpl->getInstantiatedFromMemberTemplate())
      Tmpl = M;
    return Tmpl->getTemplatedDecl();
  }
  if (const CXXRecordDecl* P = RD->getInstantiatedFromMemberClass()) return P;
  // The templated record of an instantiated member class template (reached
  // when the record itself, not a specialization of it, is the parent).
  if (const ClassTemplateDecl* CT = RD->getDescribedClassTemplate())
    if (const ClassTemplateDecl* M = CT->getInstantiatedFromMemberTemplate())
      return M->getTemplatedDecl();
  return nullptr;
}

static const FieldDecl* primaryTemplateMember(const FieldDecl* FD) {
  const auto* RD = dyn_cast_or_null<CXXRecordDecl>(FD->getParent());
  if (!RD) return FD;
  const CXXRecordDecl* Pattern = instantiationPattern(RD);
  if (!Pattern) return FD;
  // Fields have no back-pointer to the declaration they were instantiated
  // from, so match by position; recursing walks a chain of nested
  // instantiations up to the outermost pattern.
  unsigned Idx = FD->getFieldIndex();
  unsigned I = 0;
  for (const FieldDecl* PF : Pattern->fields()) {
    if (I++ == Idx) return primaryTemplateMember(PF);
  }
  return FD;
}

static const VarDecl* primaryTemplateStaticMember(const VarDecl* VD) {
  while (const VarDecl* P = VD->getInstantiatedFromStaticDataMember()) VD = P;
  return VD;
}

// Maps a method of a class-template specialization (or an instantiated member
// function template) back to the method of the primary template.
static const CXXMethodDecl* primaryTemplateMethod(const CXXMethodDecl* MD) {
  for (;;) {
    // A specialization of a member function *template* (`Init<int*>`) points
    // at its template, and that template -- when the enclosing class is itself
    // an instantiation -- at the member template written in the pattern.
    if (const FunctionTemplateSpecializationInfo* I =
            MD->getTemplateSpecializationInfo()) {
      FunctionTemplateDecl* FT = I->getTemplate();
      while (FunctionTemplateDecl* M = FT->getInstantiatedFromMemberTemplate())
        FT = M;
      if (const auto* P = dyn_cast<CXXMethodDecl>(FT->getTemplatedDecl());
          P && P != MD) {
        MD = P;
        continue;
      }
    }
    // A member function of an instantiated class points at the pattern's.
    if (const auto* P = dyn_cast_or_null<CXXMethodDecl>(
            MD->getInstantiatedFromMemberFunction())) {
      MD = P;
      continue;
    }
    return MD;
  }
}

// Collects \p MD and, transitively, every virtual function it overrides.  The
// whole family must be renamed together — renaming only some overrides would
// break `override` checking.
static void collectOverrideFamily(const CXXMethodDecl* MD,
                                  std::vector<const CXXMethodDecl*>& Out) {
  MD = primaryTemplateMethod(MD);
  Out.push_back(MD);
  for (const CXXMethodDecl* O : MD->overridden_methods())
    collectOverrideFamily(O, Out);
}

// ---------------------------------------------------------------------------
// File-set predicate
// ---------------------------------------------------------------------------

static bool shouldCollect(SourceLocation Loc, SourceManager& SM,
                          const FileSet& CollectFrom) {
  if (Loc.isInvalid()) return false;
  // Resolve through macro expansions to the file the name is actually spelled
  // in.  A declaration written as a macro *argument* is spelled in an ordinary
  // file and renames like any other.  One spelled in a macro *body* is
  // collected here too and then vetoed by the scan pass, so it is reported as a
  // skipped rename rather than silently ignored.  A name formed by token
  // pasting has no file at all (Clang's scratch buffer), and falls out here:
  // scratch space is never the main file and never in the set.
  const FileID FID = SM.getFileID(SM.getSpellingLoc(Loc));
  const bool IsMain = FID == SM.getMainFileID();
  if (CollectFrom.empty()) return IsMain;
  const FileEntry* FE = SM.getFileEntryForID(FID);
  if (!FE) return IsMain;
  llvm::StringRef RealPath = FE->tryGetRealPathName();
  if (RealPath.empty()) return IsMain;
  return CollectFrom.count(RealPath.str()) > 0;
}

// ---------------------------------------------------------------------------
// Stable location keys
// ---------------------------------------------------------------------------

// Returns a (file identifier, byte offset) key for the place \p Loc is
// *spelled*.  The identifier is the file's real path, which is stable across
// translation units and across processes -- so a token recorded while compiling
// a.cpp matches the same token when the header is compiled as its own TU, and a
// declaration one Bazel action vetoes matches the records another emitted for
// it.  For in-memory buffers with no real path (the unit-test helper) it falls
// back to the presumed file name, which is enough for the single-TU case.
static std::pair<std::string, unsigned> locKey(SourceLocation Loc,
                                               SourceManager& SM) {
  SourceLocation Spelling = SM.getSpellingLoc(Loc);
  std::pair<FileID, unsigned> Decomposed = SM.getDecomposedLoc(Spelling);
  std::string Path;
  if (const FileEntry* FE = SM.getFileEntryForID(Decomposed.first)) {
    llvm::StringRef RealPath = FE->tryGetRealPathName();
    if (!RealPath.empty()) Path = RealPath.str();
  }
  if (Path.empty()) {
    PresumedLoc PLoc = SM.getPresumedLoc(Spelling);
    Path = PLoc.isValid() ? PLoc.getFilename() : "<main>";
  }
  return std::make_pair(std::move(Path), Decomposed.second);
}

// The location to actually rewrite for a (possibly macro-expanded) token, or an
// invalid location when no byte range of any file holds the name.
//
// getFileLoc() walks macro-argument levels down to the spelling and macro-body
// levels up to the expansion, so the two agree exactly when the token was typed
// by the user -- directly, or as a macro argument forwarded through any number
// of macros, where the spelling is the call site and rewriting it is simply
// correct.  They disagree for a token spelled in a macro body (one location
// shared by every expansion, which need not agree on what it names) and for a
// ##-pasted token (whose only spelling is Clang's scratch buffer).
static SourceLocation rewriteLocFor(SourceLocation Loc, SourceManager& SM) {
  if (Loc.isInvalid()) return SourceLocation();
  if (!Loc.isMacroID()) return Loc;
  SourceLocation Spelling = SM.getSpellingLoc(Loc);
  if (SM.getFileLoc(Loc) != Spelling) return SourceLocation();
  return Spelling;
}

// locKey restricted to files the tool owns -- the key space used for cross-TU
// dependent-token resolution, where a token is only tracked if we may rewrite
// the file it lives in.
static std::optional<std::pair<std::string, unsigned>> ownedKey(
    SourceLocation Loc, SourceManager& SM, const FileSet& CollectFrom) {
  if (Loc.isInvalid()) return std::nullopt;
  const FileEntry* FE =
      SM.getFileEntryForID(SM.getFileID(SM.getSpellingLoc(Loc)));
  llvm::StringRef RealPath = FE ? FE->tryGetRealPathName() : llvm::StringRef();
  const bool Owned =
      CollectFrom.empty()
          ? SM.getFileID(SM.getSpellingLoc(Loc)) == SM.getMainFileID()
          : (!RealPath.empty() && CollectFrom.count(RealPath.str()) > 0);
  if (!Owned) return std::nullopt;
  return locKey(Loc, SM);
}

// True when \p D is a member of an explicit or partial specialization of a
// template that is declared outside the files being formatted -- std::hash<T>,
// std::formatter<T>, std::tuple_size<T>, std::numeric_limits<T>, or a
// third-party library's customisation point.  The *primary* template decides
// what such members are called and the library calls them by those names, so
// renaming them is another complete rename that does not compile.  A
// specialization of one of our own templates is not affected: its members are
// unrelated declarations that rename on their own.
static bool isMemberOfForeignSpecialization(const NamedDecl* D,
                                            SourceManager& SM,
                                            const FileSet& CollectFrom) {
  const auto* Spec =
      dyn_cast_or_null<ClassTemplateSpecializationDecl>(D->getDeclContext());
  if (!Spec) return false;
  const ClassTemplateDecl* Tmpl = Spec->getSpecializedTemplate();
  return Tmpl && !shouldCollect(Tmpl->getLocation(), SM, CollectFrom);
}

// True when \p D is the outermost declaration of a template instantiation --
// the point at which a RecursiveASTVisitor that visits instantiations leaves
// the code the user wrote for code the compiler made from it.
static bool isInstantiationRoot(const Decl* D) {
  if (const auto* FD = dyn_cast<FunctionDecl>(D))
    return FD->isTemplateInstantiation() ||
           FD->getInstantiatedFromMemberFunction() != nullptr;
  if (const auto* RD = dyn_cast<CXXRecordDecl>(D)) {
    const TemplateSpecializationKind K = RD->getTemplateSpecializationKind();
    return (K != TSK_Undeclared && K != TSK_ExplicitSpecialization) ||
           RD->getInstantiatedFromMemberClass() != nullptr;
  }
  if (const auto* VD = dyn_cast<VarDecl>(D))
    return VD->getInstantiatedFromStaticDataMember() != nullptr ||
           isa<VarTemplateSpecializationDecl>(VD);
  return false;
}

// The declaration kinds the by-name backstops apply to: class members.  A
// local or parameter of an instantiated function is a fresh declaration too,
// but every use of it is in the pattern, which is what the rewrite pass walks,
// so it is never the thing that gets left behind.
static bool isClassMemberDecl(const Decl* D) {
  if (isa<FieldDecl>(D) || isa<CXXMethodDecl>(D)) return true;
  const auto* VD = dyn_cast<VarDecl>(D);
  return VD && VD->isStaticDataMember();
}

// True when \p D lives inside a template instantiation -- a member of an
// implicitly instantiated class (or of a class nested in one, an anonymous
// union included), or of an instantiated member function.  Such a declaration
// should have been mapped back to its pattern before it reached the rename map;
// one that was not is a mapping failure, not a different entity.
static bool isInTemplateInstantiation(const Decl* D) {
  // A function template specialization is an instantiation in its own right.
  if (const auto* FD = dyn_cast<FunctionDecl>(D))
    if (FD->isTemplateInstantiation()) return true;
  for (const DeclContext* DC = D->getDeclContext(); DC; DC = DC->getParent()) {
    if (const auto* RD = dyn_cast<CXXRecordDecl>(DC)) {
      const TemplateSpecializationKind K = RD->getTemplateSpecializationKind();
      if (K != TSK_Undeclared && K != TSK_ExplicitSpecialization) return true;
      if (RD->getInstantiatedFromMemberClass()) return true;
    } else if (const auto* FD = dyn_cast<FunctionDecl>(DC)) {
      if (FD->isTemplateInstantiation()) return true;
    }
  }
  return false;
}

// ---------------------------------------------------------------------------
// Veto key for a rename
// ---------------------------------------------------------------------------

// The key under which a declaration's rename is vetoed, and under which its
// edit records name their owner.  For a virtual function it is the base-most
// declaration of the override hierarchy, so that a veto discovered on *any*
// override suppresses the whole family -- including in records emitted by
// another process, which never sees which part of the hierarchy this TU had in
// view.  collectOverrideFamily() walks upwards only, so every override's
// family contains the same roots and all of them agree on this key.
static std::pair<std::string, unsigned> renameOwnerKey(const Decl* D,
                                                       SourceManager& SM) {
  if (const auto* MD = dyn_cast<CXXMethodDecl>(D)) {
    std::vector<const CXXMethodDecl*> Family;
    collectOverrideFamily(MD, Family);
    std::optional<std::pair<std::string, unsigned>> Root;
    for (const CXXMethodDecl* M : Family) {
      if (M->size_overridden_methods() != 0) continue;
      std::pair<std::string, unsigned> K = locKey(M->getLocation(), SM);
      if (!Root || K < *Root) Root = std::move(K);
    }
    if (Root) return *Root;
  }
  return locKey(D->getLocation(), SM);
}

// Records a veto against renaming \p Key.  Returns true if this is the first
// veto for that declaration, so the caller can report it once.
static bool addRenameVeto(RenameVetoes* Vetoes, const Decl* Key,
                          SourceManager& SM, llvm::StringRef OldName,
                          const std::string& Reason) {
  if (!Vetoes) return false;
  std::pair<std::string, unsigned> Owner = renameOwnerKey(Key, SM);
  std::string File = relativizeToCwd(Owner.first);
  return Vetoes
      ->try_emplace(std::make_pair(File, Owner.second),
                    RenameVeto{File, Owner.second, OldName.str(), Reason})
      .second;
}

// The class a member's name is looked up in: the nearest enclosing record that
// is not an anonymous struct or union (whose members are found in the
// enclosing class).
static const CXXRecordDecl* lookupHomeOf(const NamedDecl* Member) {
  for (const DeclContext* DC = Member->getDeclContext(); DC;
       DC = DC->getParent()) {
    const auto* RD = dyn_cast<CXXRecordDecl>(DC);
    if (!RD) return nullptr;
    if (!RD->isAnonymousStructOrUnion()) return RD;
  }
  return nullptr;
}

// ---------------------------------------------------------------------------
// Macro arguments the preprocessor consumed (see ConsumedMacroArgs)
// ---------------------------------------------------------------------------
//
// For every function-like macro expansion, the tokens of each argument whose
// parameter the body only ever pastes (`##` on either side), stringizes (`#`)
// or never mentions are recorded by their spelling location.  Those tokens
// are the ones the preprocessor never emits as themselves: what reaches the
// parser is the pasted identifier or the string literal, and neither is a
// reference at the argument's spelling.  A parameter used plainly anywhere in
// the body -- even once, even alongside a paste -- is not consumed: its
// argument is emitted, and if that emission is a reference the tool does not
// understand, the audit must still see it.  The variadic parameter is never
// consumed: `, ## __VA_ARGS__` is the comma-swallowing idiom, not a paste.
class ConsumedMacroArgsCallbacks : public PPCallbacks {
 public:
  ConsumedMacroArgsCallbacks(SourceManager& SM, ConsumedMacroArgs& Out)
      : SM(SM), Out(Out) {}

  void MacroExpands(const Token&, const MacroDefinition& MD, SourceRange,
                    const MacroArgs* Args) override {
    const MacroInfo* MI = MD.getMacroInfo();
    if (!MI || !Args || !MI->isFunctionLike()) return;
    const ParamUse Use = paramUse(MI);
    const unsigned N =
        std::min<unsigned>(MI->getNumParams(), Args->getNumMacroArguments());
    for (unsigned I = 0; I < N; ++I) {
      if (!Use.Consumed[I] && !Use.Pasted[I]) continue;
      for (const Token* T = Args->getUnexpArgument(I); T && T->isNot(tok::eof);
           ++T) {
        if (!T->is(tok::identifier)) continue;
        // A nested invocation's argument came out of an enclosing expansion;
        // getFileLoc walks the argument levels back to where it was written.
        const SourceLocation L = SM.getFileLoc(T->getLocation());
        if (L.isInvalid()) continue;
        if (Use.Consumed[I]) Out.Tokens.insert(SM.getDecomposedLoc(L));
        if (Use.Pasted[I]) Out.Pasted.insert(SM.getDecomposedLoc(L));
      }
    }
  }

 private:
  // Per parameter: only ever pasted / stringized / unused (Consumed), and
  // pasted at least once (Pasted).  The two overlap but neither implies the
  // other: `int n; int n##_count;` is pasted and not consumed.
  struct ParamUse {
    llvm::BitVector Consumed, Pasted;
  };

  ParamUse paramUse(const MacroInfo* MI) {
    auto It = Cache.find(MI);
    if (It != Cache.end()) return It->second;
    ParamUse Use{llvm::BitVector(MI->getNumParams(), true),
                 llvm::BitVector(MI->getNumParams(), false)};
    const ArrayRef<const IdentifierInfo*> Params = MI->params();
    if (MI->isVariadic() && !Params.empty())
      Use.Consumed[Params.size() - 1] = false;
    const ArrayRef<Token> Toks = MI->tokens();
    for (size_t I = 0; I < Toks.size(); ++I) {
      if (!Toks[I].is(tok::identifier)) continue;
      const auto* P = llvm::find(Params, Toks[I].getIdentifierInfo());
      if (P == Params.end()) continue;
      const size_t Idx = P - Params.begin();
      const bool Stringized = I > 0 && Toks[I - 1].is(tok::hash);
      const bool Pasted =
          (I > 0 && Toks[I - 1].is(tok::hashhash)) ||
          (I + 1 < Toks.size() && Toks[I + 1].is(tok::hashhash));
      if (Pasted && !(MI->isVariadic() && Idx + 1 == Params.size()))
        Use.Pasted[Idx] = true;
      if (!Stringized && !Pasted) Use.Consumed[Idx] = false;
    }
    Cache[MI] = Use;
    return Use;
  }

  SourceManager& SM;
  ConsumedMacroArgs& Out;
  llvm::DenseMap<const MacroInfo*, ParamUse> Cache;
};

